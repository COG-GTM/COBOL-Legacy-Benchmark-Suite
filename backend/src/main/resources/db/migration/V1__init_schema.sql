-- ============================================================
-- Investment Portfolio Management System - Database Schema
-- Migrated from DB2 for z/OS + VSAM to PostgreSQL/H2
-- Source: src/database/db2/db2-definitions.sql, POSHIST.sql, ERRLOG.sql
-- ============================================================

-- ============================================================
-- PORTFOLIO_MASTER (from DB2 PORTFOLIO_MASTER table)
-- ============================================================
CREATE TABLE IF NOT EXISTS portfolio_master (
    portfolio_id      VARCHAR(8)      NOT NULL,
    account_type      VARCHAR(2)      NOT NULL,
    branch_id         VARCHAR(2)      NOT NULL,
    client_id         VARCHAR(10)     NOT NULL,
    portfolio_name    VARCHAR(50)     NOT NULL,
    currency_code     VARCHAR(3)      NOT NULL DEFAULT 'USD',
    risk_level        VARCHAR(1)      NOT NULL DEFAULT 'M',
    status            VARCHAR(1)      NOT NULL DEFAULT 'A',
    open_date         DATE            NOT NULL,
    close_date        DATE,
    last_maint_date   TIMESTAMP       NOT NULL DEFAULT CURRENT_TIMESTAMP,
    last_maint_user   VARCHAR(8)      NOT NULL,
    PRIMARY KEY (portfolio_id)
);

-- ============================================================
-- INVESTMENT_POSITIONS (from DB2 INVESTMENT_POSITIONS + VSAM POSMSTRE)
-- Composite key: portfolio_id + investment_id + position_date
-- Maps COBOL copybook POSREC
-- ============================================================
CREATE TABLE IF NOT EXISTS investment_positions (
    portfolio_id      VARCHAR(8)      NOT NULL,
    investment_id     VARCHAR(10)     NOT NULL,
    position_date     DATE            NOT NULL,
    quantity          DECIMAL(18,4)   NOT NULL DEFAULT 0,
    cost_basis        DECIMAL(18,2)   NOT NULL DEFAULT 0,
    market_value      DECIMAL(18,2)   NOT NULL DEFAULT 0,
    currency_code     VARCHAR(3)      NOT NULL DEFAULT 'USD',
    status            VARCHAR(1)      NOT NULL DEFAULT 'A',
    last_maint_date   TIMESTAMP       NOT NULL DEFAULT CURRENT_TIMESTAMP,
    last_maint_user   VARCHAR(8)      NOT NULL,
    PRIMARY KEY (portfolio_id, investment_id, position_date),
    FOREIGN KEY (portfolio_id) REFERENCES portfolio_master(portfolio_id)
);

-- ============================================================
-- TRANSACTION_HISTORY (from DB2 TRANSACTION_HISTORY + VSAM TRANHIST)
-- Maps COBOL copybook TRNREC
-- ============================================================
CREATE TABLE IF NOT EXISTS transaction_history (
    transaction_id    VARCHAR(20)     NOT NULL,
    portfolio_id      VARCHAR(8)      NOT NULL,
    transaction_date  DATE            NOT NULL,
    transaction_time  TIME            NOT NULL,
    investment_id     VARCHAR(10)     NOT NULL,
    transaction_type  VARCHAR(2)      NOT NULL,
    quantity          DECIMAL(18,4)   NOT NULL DEFAULT 0,
    price             DECIMAL(18,4)   NOT NULL DEFAULT 0,
    amount            DECIMAL(18,2)   NOT NULL DEFAULT 0,
    currency_code     VARCHAR(3)      NOT NULL DEFAULT 'USD',
    status            VARCHAR(1)      NOT NULL DEFAULT 'P',
    process_date      TIMESTAMP       NOT NULL DEFAULT CURRENT_TIMESTAMP,
    process_user      VARCHAR(8)      NOT NULL,
    PRIMARY KEY (transaction_id),
    FOREIGN KEY (portfolio_id) REFERENCES portfolio_master(portfolio_id)
);

-- ============================================================
-- POSITION_HISTORY (from DB2 POSHIST table)
-- Maps COBOL copybook HISTREC
-- ============================================================
CREATE TABLE IF NOT EXISTS position_history (
    id                BIGINT          GENERATED BY DEFAULT AS IDENTITY,
    account_no        VARCHAR(8)      NOT NULL,
    portfolio_id      VARCHAR(10)     NOT NULL,
    trans_date        DATE            NOT NULL,
    trans_time        TIME,
    trans_type        VARCHAR(2)      NOT NULL,
    security_id       VARCHAR(12)     NOT NULL,
    quantity          DECIMAL(15,3)   NOT NULL DEFAULT 0,
    price             DECIMAL(15,3)   NOT NULL DEFAULT 0,
    amount            DECIMAL(15,2)   NOT NULL DEFAULT 0,
    fees              DECIMAL(15,2)   NOT NULL DEFAULT 0,
    total_amount      DECIMAL(15,2)   NOT NULL DEFAULT 0,
    cost_basis        DECIMAL(15,2)   NOT NULL DEFAULT 0,
    gain_loss         DECIMAL(15,2)   NOT NULL DEFAULT 0,
    process_date      DATE            NOT NULL,
    process_time      TIME            NOT NULL,
    program_id        VARCHAR(8)      NOT NULL,
    user_id           VARCHAR(8)      NOT NULL,
    audit_timestamp   TIMESTAMP       NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (id)
);

-- ============================================================
-- ERROR_LOG (from DB2 ERRLOG table)
-- ============================================================
CREATE TABLE IF NOT EXISTS error_log (
    id                BIGINT          GENERATED BY DEFAULT AS IDENTITY,
    error_timestamp   TIMESTAMP       NOT NULL DEFAULT CURRENT_TIMESTAMP,
    program_id        VARCHAR(8)      NOT NULL,
    error_type        VARCHAR(1)      NOT NULL,
    error_severity    INT             NOT NULL,
    error_code        VARCHAR(8)      NOT NULL,
    error_message     VARCHAR(200)    NOT NULL,
    process_date      DATE            NOT NULL,
    process_time      TIME,
    user_id           VARCHAR(8)      NOT NULL,
    additional_info   VARCHAR(500),
    PRIMARY KEY (id)
);

-- ============================================================
-- AUDIT_LOG (from SECMGR COBOL program - replaces AUDITLOG table)
-- ============================================================
CREATE TABLE IF NOT EXISTS audit_log (
    id                BIGINT          GENERATED BY DEFAULT AS IDENTITY,
    audit_timestamp   TIMESTAMP       NOT NULL DEFAULT CURRENT_TIMESTAMP,
    user_id           VARCHAR(8)      NOT NULL,
    terminal_id       VARCHAR(4),
    transaction_id    VARCHAR(4),
    program_name      VARCHAR(8),
    access_type       VARCHAR(8),
    resource_name     VARCHAR(50),
    action            VARCHAR(50),
    details           VARCHAR(500),
    ip_address        VARCHAR(45),
    PRIMARY KEY (id)
);

-- ============================================================
-- BATCH_CONTROL (from VSAM BCHCTL file)
-- Maps COBOL copybook BCHCTL
-- ============================================================
CREATE TABLE IF NOT EXISTS batch_control (
    id                BIGINT          GENERATED BY DEFAULT AS IDENTITY,
    process_date      DATE            NOT NULL,
    process_id        VARCHAR(8)      NOT NULL,
    status            VARCHAR(1)      NOT NULL DEFAULT 'W',
    start_time        TIMESTAMP,
    end_time          TIMESTAMP,
    record_count      BIGINT          DEFAULT 0,
    error_count       BIGINT          DEFAULT 0,
    last_position     BIGINT          DEFAULT 0,
    return_code       INT             DEFAULT 0,
    message           VARCHAR(200),
    PRIMARY KEY (id)
);

-- ============================================================
-- APP_USER (for Spring Security JWT auth - replaces RACF)
-- ============================================================
CREATE TABLE IF NOT EXISTS app_user (
    id                BIGINT          GENERATED BY DEFAULT AS IDENTITY,
    username          VARCHAR(50)     NOT NULL UNIQUE,
    password          VARCHAR(255)    NOT NULL,
    email             VARCHAR(100),
    full_name         VARCHAR(100),
    role              VARCHAR(20)     NOT NULL DEFAULT 'USER',
    enabled           BOOLEAN         NOT NULL DEFAULT TRUE,
    created_date      TIMESTAMP       NOT NULL DEFAULT CURRENT_TIMESTAMP,
    last_login_date   TIMESTAMP,
    PRIMARY KEY (id)
);

-- ============================================================
-- INDEXES (from DB2 index definitions)
-- ============================================================
CREATE INDEX IF NOT EXISTS idx_port_master_client ON portfolio_master (client_id, status);
CREATE INDEX IF NOT EXISTS idx_positions_date ON investment_positions (position_date, portfolio_id);
CREATE INDEX IF NOT EXISTS idx_trans_hist_port ON transaction_history (portfolio_id, transaction_date);
CREATE INDEX IF NOT EXISTS idx_trans_hist_date ON transaction_history (transaction_date, portfolio_id);
CREATE INDEX IF NOT EXISTS idx_poshist_security ON position_history (security_id, trans_date);
CREATE INDEX IF NOT EXISTS idx_poshist_process ON position_history (process_date, program_id);
CREATE INDEX IF NOT EXISTS idx_errlog_date ON error_log (process_date, error_severity);
CREATE INDEX IF NOT EXISTS idx_audit_user ON audit_log (user_id, audit_timestamp);
CREATE INDEX IF NOT EXISTS idx_batch_control_date ON batch_control (process_date, process_id);
