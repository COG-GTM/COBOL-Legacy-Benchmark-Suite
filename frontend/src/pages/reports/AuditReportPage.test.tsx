import { screen } from '@testing-library/react';
import userEvent from '@testing-library/user-event';
import { describe, it, expect, vi } from 'vitest';
import { AuditReportPage } from './AuditReportPage';
import { renderWithRouter } from '@/test/helpers';

describe('AuditReportPage', () => {
  it('renders the page title', () => {
    renderWithRouter(<AuditReportPage />);
    expect(screen.getByText('Audit Report')).toBeInTheDocument();
  });

  it('renders the description', () => {
    renderWithRouter(<AuditReportPage />);
    expect(screen.getByText('Security events and error logs generated by RPTAUD00')).toBeInTheDocument();
  });

  it('renders download CSV button', () => {
    renderWithRouter(<AuditReportPage />);
    expect(screen.getByRole('button', { name: /download csv/i })).toBeInTheDocument();
  });

  it('renders summary stats cards', () => {
    renderWithRouter(<AuditReportPage />);
    expect(screen.getByText('Total Entries')).toBeInTheDocument();
    // "Success" appears in both stat card and filter option, so use getAllByText
    expect(screen.getAllByText('Success').length).toBeGreaterThanOrEqual(1);
    expect(screen.getByText('Failures')).toBeInTheDocument();
    expect(screen.getByText('Failure Rate')).toBeInTheDocument();
  });

  it('renders filter controls', () => {
    renderWithRouter(<AuditReportPage />);
    expect(screen.getByLabelText('Program')).toBeInTheDocument();
    expect(screen.getByLabelText('Status')).toBeInTheDocument();
    expect(screen.getByLabelText('From')).toBeInTheDocument();
    expect(screen.getByLabelText('To')).toBeInTheDocument();
  });

  it('renders data table columns', () => {
    renderWithRouter(<AuditReportPage />);
    // "Timestamp" in column header
    expect(screen.getByText('Timestamp')).toBeInTheDocument();
    // "Program" appears in both the label and column, use getAllByText
    expect(screen.getAllByText('Program').length).toBeGreaterThanOrEqual(1);
    expect(screen.getByText('Action')).toBeInTheDocument();
    // "Status" appears in both label and column
    expect(screen.getAllByText('Status').length).toBeGreaterThanOrEqual(1);
  });

  it('filters by program', async () => {
    const user = userEvent.setup();
    renderWithRouter(<AuditReportPage />);
    const programFilter = screen.getByLabelText('Program');
    await user.selectOptions(programFilter, 'TRNVAL00');
    const cells = screen.getAllByText('TRNVAL00');
    expect(cells.length).toBeGreaterThan(0);
  });

  it('filters by status', async () => {
    const user = userEvent.setup();
    renderWithRouter(<AuditReportPage />);
    const statusFilter = screen.getByLabelText('Status');
    await user.selectOptions(statusFilter, 'Success');
    const succBadges = screen.getAllByText('SUCC');
    expect(succBadges.length).toBeGreaterThan(0);
    expect(screen.queryByText('FAIL')).not.toBeInTheDocument();
  });

  it('calls downloadCsv on button click', async () => {
    const user = userEvent.setup();
    renderWithRouter(<AuditReportPage />);
    const clickSpy = vi.fn();
    const origCreate = document.createElement.bind(document);
    vi.spyOn(document, 'createElement').mockImplementation((tag: string) => {
      const el = origCreate(tag);
      if (tag === 'a') el.click = clickSpy;
      return el;
    });
    await user.click(screen.getByRole('button', { name: /download csv/i }));
    expect(clickSpy).toHaveBeenCalled();
    vi.restoreAllMocks();
  });
});
