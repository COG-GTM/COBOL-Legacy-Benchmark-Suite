import { useState, useMemo } from 'react';
import { Download, FileText, ChevronLeft, ChevronRight } from 'lucide-react';
import { PageHeader } from '@/components/ui/PageHeader';
import { Card } from '@/components/ui/Card';
import { DataTable } from '@/components/ui/DataTable';
import type { Column } from '@/components/ui/DataTable';
import { StatusBadge, getAuditStatusVariant } from '@/components/ui/StatusBadge';
import { auditEntries } from '@/data/mockData';
import type { AuditEntry } from '@/data/types';

type AuditRow = AuditEntry & Record<string, unknown>;

const PROGRAMS = ['All', 'TRNVAL00', 'POSUPD00', 'HISTLD00', 'RPTPOS00', 'RPTAUD00', 'RPTSTA00'] as const;
const PAGE_SIZE = 10;

function downloadCsv(data: AuditEntry[], filename: string) {
  const headers = ['Timestamp', 'Program', 'Type', 'Action', 'Status', 'Portfolio ID', 'Account No', 'Message'];
  const rows = data.map((r) => [
    r.timestamp,
    r.program,
    r.type,
    r.action,
    r.status,
    r.portfolioId,
    r.accountNo,
    `"${r.message.replace(/"/g, '""')}"`,
  ]);
  const csv = [headers.join(','), ...rows.map((r) => r.join(','))].join('\n');
  const blob = new Blob([csv], { type: 'text/csv;charset=utf-8;' });
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = filename;
  a.click();
  URL.revokeObjectURL(url);
}

export function AuditReportPage() {
  const [programFilter, setProgramFilter] = useState('All');
  const [statusFilter, setStatusFilter] = useState('All');
  const [dateFrom, setDateFrom] = useState('');
  const [dateTo, setDateTo] = useState('');
  const [page, setPage] = useState(0);

  const filteredData = useMemo(() => {
    let data = [...auditEntries];
    if (programFilter !== 'All') {
      data = data.filter((e) => e.program === programFilter);
    }
    if (statusFilter === 'Success') {
      data = data.filter((e) => e.status === 'SUCC');
    } else if (statusFilter === 'Failure') {
      data = data.filter((e) => e.status === 'FAIL');
    }
    if (dateFrom) {
      data = data.filter((e) => e.timestamp >= dateFrom);
    }
    if (dateTo) {
      const toEnd = dateTo + ' 23:59:59';
      data = data.filter((e) => e.timestamp <= toEnd);
    }
    return data;
  }, [programFilter, statusFilter, dateFrom, dateTo]);

  const stats = useMemo(() => {
    const total = filteredData.length;
    const successCount = filteredData.filter((e) => e.status === 'SUCC').length;
    const failureCount = filteredData.filter((e) => e.status === 'FAIL').length;
    const failureRate = total > 0 ? (failureCount / total) * 100 : 0;
    return { total, successCount, failureCount, failureRate };
  }, [filteredData]);

  const totalPages = Math.max(1, Math.ceil(filteredData.length / PAGE_SIZE));
  const effectivePage = Math.min(page, totalPages - 1);
  const pagedData = useMemo(
    () => filteredData.slice(effectivePage * PAGE_SIZE, (effectivePage + 1) * PAGE_SIZE),
    [filteredData, effectivePage],
  );

  const columns: Column<AuditRow>[] = [
    { key: 'timestamp', header: 'Timestamp', sortable: true, render: (r) => (
      <span className="font-mono text-xs">{r.timestamp}</span>
    )},
    { key: 'program', header: 'Program', sortable: true, render: (r) => (
      <span className="font-mono text-sm">{r.program}</span>
    )},
    { key: 'type', header: 'Type', sortable: true },
    { key: 'action', header: 'Action', sortable: true, render: (r) => (
      <span className="text-xs">{r.action}</span>
    )},
    { key: 'status', header: 'Status', sortable: true, render: (r) => (
      <StatusBadge label={r.status} variant={getAuditStatusVariant(r.status)} />
    )},
    { key: 'portfolioId', header: 'Portfolio ID', sortable: true, render: (r) => (
      <span className="font-mono text-sm">{r.portfolioId || '—'}</span>
    )},
    { key: 'message', header: 'Message', sortable: false, render: (r) => (
      <span className="text-xs text-slate-600 max-w-xs truncate block" title={r.message}>{r.message}</span>
    )},
  ];

  const selectClass = 'px-3 py-2 text-sm border border-slate-300 rounded-lg bg-white text-slate-900 focus:outline-none focus:ring-2 focus:ring-blue-500 focus:border-blue-500';
  const today = new Date().toLocaleDateString('en-US', { year: 'numeric', month: 'long', day: 'numeric' });
  const now = new Date().toLocaleTimeString('en-US', { hour: '2-digit', minute: '2-digit' });

  return (
    <div>
      <PageHeader
        title="Audit Report"
        description="Security events and error logs generated by RPTAUD00"
        actions={
          <button
            onClick={() => downloadCsv(filteredData, `audit-report-${new Date().toISOString().slice(0, 10)}.csv`)}
            className="inline-flex items-center gap-2 px-4 py-2 text-sm font-medium text-white bg-blue-600 rounded-lg hover:bg-blue-700 transition-colors"
          >
            <Download className="w-4 h-4" />
            Download CSV
          </button>
        }
      />

      <div className="flex items-center gap-3 mb-6 text-sm text-slate-500">
        <FileText className="w-4 h-4" />
        <span>Generated: {today} at {now}</span>
      </div>

      <div className="grid grid-cols-1 sm:grid-cols-2 lg:grid-cols-4 gap-4 mb-6">
        <div className="bg-white rounded-lg border border-slate-200 shadow-sm p-4">
          <p className="text-sm font-medium text-slate-500">Total Entries</p>
          <p className="text-2xl font-bold text-slate-900 mt-1">{stats.total}</p>
        </div>
        <div className="bg-white rounded-lg border border-slate-200 shadow-sm p-4">
          <p className="text-sm font-medium text-slate-500">Success</p>
          <p className="text-2xl font-bold text-emerald-600 mt-1">{stats.successCount}</p>
        </div>
        <div className="bg-white rounded-lg border border-slate-200 shadow-sm p-4">
          <p className="text-sm font-medium text-slate-500">Failures</p>
          <p className="text-2xl font-bold text-red-600 mt-1">{stats.failureCount}</p>
        </div>
        <div className="bg-white rounded-lg border border-slate-200 shadow-sm p-4">
          <p className="text-sm font-medium text-slate-500">Failure Rate</p>
          <p className="text-2xl font-bold text-slate-900 mt-1">{stats.failureRate.toFixed(1)}%</p>
        </div>
      </div>

      <div className="flex flex-wrap items-end gap-4 mb-6">
        <div>
          <label htmlFor="program-filter" className="block text-sm font-medium text-slate-700 mb-1">Program</label>
          <select id="program-filter" value={programFilter} onChange={(e) => setProgramFilter(e.target.value)} className={selectClass}>
            {PROGRAMS.map((p) => <option key={p} value={p}>{p}</option>)}
          </select>
        </div>
        <div>
          <label htmlFor="status-filter" className="block text-sm font-medium text-slate-700 mb-1">Status</label>
          <select id="status-filter" value={statusFilter} onChange={(e) => setStatusFilter(e.target.value)} className={selectClass}>
            <option value="All">All</option>
            <option value="Success">Success</option>
            <option value="Failure">Failure</option>
          </select>
        </div>
        <div>
          <label htmlFor="date-from" className="block text-sm font-medium text-slate-700 mb-1">From</label>
          <input id="date-from" type="date" value={dateFrom} onChange={(e) => setDateFrom(e.target.value)} className={selectClass} />
        </div>
        <div>
          <label htmlFor="date-to" className="block text-sm font-medium text-slate-700 mb-1">To</label>
          <input id="date-to" type="date" value={dateTo} onChange={(e) => setDateTo(e.target.value)} className={selectClass} />
        </div>
      </div>

      <Card>
        <div className="-m-6">
          <DataTable<AuditRow>
            columns={columns}
            data={pagedData as AuditRow[]}
            keyExtractor={(r) => `${r.timestamp}-${r.program}-${r.action}`}
            emptyMessage="No audit entries match the selected filters"
          />
        </div>
      </Card>

      {filteredData.length > PAGE_SIZE && (
        <div className="flex items-center justify-between mt-4 text-sm text-slate-600">
          <span>
            Showing {effectivePage * PAGE_SIZE + 1}–{Math.min((effectivePage + 1) * PAGE_SIZE, filteredData.length)} of {filteredData.length} entries
          </span>
          <div className="flex items-center gap-2">
            <button
              onClick={() => setPage((p) => Math.max(0, p - 1))}
              disabled={effectivePage === 0}
              className="inline-flex items-center gap-1 px-3 py-1.5 rounded-lg border border-slate-300 bg-white hover:bg-slate-50 disabled:opacity-50 disabled:cursor-not-allowed transition-colors"
            >
              <ChevronLeft className="w-4 h-4" />
              Previous
            </button>
            <span className="px-3 py-1.5">
              Page {effectivePage + 1} of {totalPages}
            </span>
            <button
              onClick={() => setPage((p) => Math.min(totalPages - 1, p + 1))}
              disabled={effectivePage >= totalPages - 1}
              className="inline-flex items-center gap-1 px-3 py-1.5 rounded-lg border border-slate-300 bg-white hover:bg-slate-50 disabled:opacity-50 disabled:cursor-not-allowed transition-colors"
            >
              Next
              <ChevronRight className="w-4 h-4" />
            </button>
          </div>
        </div>
      )}
    </div>
  );
}
