import { screen } from '@testing-library/react';
import userEvent from '@testing-library/user-event';
import { describe, it, expect, vi } from 'vitest';
import { PositionReportPage } from './PositionReportPage';
import { renderWithRouter } from '@/test/helpers';

describe('PositionReportPage', () => {
  it('renders the page title', () => {
    renderWithRouter(<PositionReportPage />);
    expect(screen.getByText('Position Report')).toBeInTheDocument();
  });

  it('renders the description', () => {
    renderWithRouter(<PositionReportPage />);
    expect(screen.getByText('Portfolio valuations generated by RPTPOS00')).toBeInTheDocument();
  });

  it('renders download CSV button', () => {
    renderWithRouter(<PositionReportPage />);
    expect(screen.getByRole('button', { name: /download csv/i })).toBeInTheDocument();
  });

  it('renders portfolio filter dropdown', () => {
    renderWithRouter(<PositionReportPage />);
    expect(screen.getByLabelText('Filter by Portfolio:')).toBeInTheDocument();
  });

  it('shows data table with position data', () => {
    renderWithRouter(<PositionReportPage />);
    expect(screen.getByText('Portfolio')).toBeInTheDocument();
    expect(screen.getByText('Fund ID')).toBeInTheDocument();
    expect(screen.getByText('Current Value')).toBeInTheDocument();
  });

  it('filters by portfolio when selected', async () => {
    const user = userEvent.setup();
    renderWithRouter(<PositionReportPage />);
    const filter = screen.getByLabelText('Filter by Portfolio:');
    await user.selectOptions(filter, 'PORT0001');
    // Only PORT0001 rows should be visible
    const rows = screen.getAllByText('PORT0001');
    expect(rows.length).toBeGreaterThan(0);
    expect(screen.queryByText('PORT0003')).not.toBeInTheDocument();
  });

  it('shows all portfolios when filter is reset', async () => {
    const user = userEvent.setup();
    renderWithRouter(<PositionReportPage />);
    const filter = screen.getByLabelText('Filter by Portfolio:');
    await user.selectOptions(filter, 'PORT0001');
    await user.selectOptions(filter, '');
    expect(screen.getAllByRole('row').length).toBeGreaterThan(3);
  });

  it('calls downloadCsv on button click', async () => {
    const user = userEvent.setup();
    renderWithRouter(<PositionReportPage />);
    const clickSpy = vi.fn();
    const origCreate = document.createElement.bind(document);
    vi.spyOn(document, 'createElement').mockImplementation((tag: string) => {
      const el = origCreate(tag);
      if (tag === 'a') el.click = clickSpy;
      return el;
    });
    await user.click(screen.getByRole('button', { name: /download csv/i }));
    expect(clickSpy).toHaveBeenCalled();
    vi.restoreAllMocks();
  });
});
