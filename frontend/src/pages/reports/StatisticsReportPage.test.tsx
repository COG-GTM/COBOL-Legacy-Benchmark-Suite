import { screen } from '@testing-library/react';
import userEvent from '@testing-library/user-event';
import { describe, it, expect, vi } from 'vitest';
import { StatisticsReportPage } from './StatisticsReportPage';
import { renderWithRouter } from '@/test/helpers';
import type { ReactNode } from 'react';

// Mock recharts to avoid canvas/SVG issues in jsdom
vi.mock('recharts', () => ({
  ResponsiveContainer: ({ children }: { children: ReactNode }) => <div data-testid="chart-container">{children}</div>,
  BarChart: ({ children }: { children: ReactNode }) => <div data-testid="bar-chart">{children}</div>,
  Bar: () => <div data-testid="bar" />,
  XAxis: () => <div />,
  YAxis: () => <div />,
  CartesianGrid: () => <div />,
  Tooltip: () => <div />,
}));

describe('StatisticsReportPage', () => {
  it('renders the page title', () => {
    renderWithRouter(<StatisticsReportPage />);
    expect(screen.getByText('Statistics Report')).toBeInTheDocument();
  });

  it('renders the description', () => {
    renderWithRouter(<StatisticsReportPage />);
    expect(screen.getByText('System performance metrics generated by RPTSTA00')).toBeInTheDocument();
  });

  it('renders download CSV button', () => {
    renderWithRouter(<StatisticsReportPage />);
    expect(screen.getByRole('button', { name: /download csv/i })).toBeInTheDocument();
  });

  it('renders KPI cards', () => {
    renderWithRouter(<StatisticsReportPage />);
    expect(screen.getByText('Transactions Today')).toBeInTheDocument();
    // "1,247" appears in both KPI card and metrics table
    expect(screen.getAllByText('1,247').length).toBeGreaterThanOrEqual(1);
    // "Avg Response Time" appears in both KPI card and metrics table
    expect(screen.getAllByText('Avg Response Time').length).toBeGreaterThanOrEqual(1);
    expect(screen.getByText('145ms')).toBeInTheDocument();
    // "Error Rate" also appears in both
    expect(screen.getAllByText('Error Rate').length).toBeGreaterThanOrEqual(1);
    expect(screen.getAllByText('0.24%').length).toBeGreaterThanOrEqual(1);
    expect(screen.getByText('System Uptime')).toBeInTheDocument();
    expect(screen.getByText('99.97%')).toBeInTheDocument();
  });

  it('renders the chart container', () => {
    renderWithRouter(<StatisticsReportPage />);
    expect(screen.getByText('Daily Transaction Volume (Last 30 Days)')).toBeInTheDocument();
    expect(screen.getByTestId('chart-container')).toBeInTheDocument();
  });

  it('renders system metrics table', () => {
    renderWithRouter(<StatisticsReportPage />);
    expect(screen.getByText('System Metrics')).toBeInTheDocument();
    expect(screen.getByText('Metric')).toBeInTheDocument();
    expect(screen.getByText('Current Value')).toBeInTheDocument();
    expect(screen.getByText('Threshold')).toBeInTheDocument();
  });

  it('renders metric data rows', () => {
    renderWithRouter(<StatisticsReportPage />);
    expect(screen.getByText('Transactions/Day')).toBeInTheDocument();
    // Some metric names appear in KPI cards too, use getAllByText
    expect(screen.getAllByText('Avg Response Time').length).toBeGreaterThanOrEqual(2);
    expect(screen.getByText('CPU Utilization')).toBeInTheDocument();
  });

  it('shows OK/Warning status based on threshold', () => {
    renderWithRouter(<StatisticsReportPage />);
    const okBadges = screen.getAllByText('OK');
    expect(okBadges.length).toBeGreaterThan(0);
  });

  it('calls downloadCsv on button click', async () => {
    const user = userEvent.setup();
    renderWithRouter(<StatisticsReportPage />);
    const clickSpy = vi.fn();
    const origCreate = document.createElement.bind(document);
    vi.spyOn(document, 'createElement').mockImplementation((tag: string) => {
      const el = origCreate(tag);
      if (tag === 'a') el.click = clickSpy;
      return el;
    });
    await user.click(screen.getByRole('button', { name: /download csv/i }));
    expect(clickSpy).toHaveBeenCalled();
    vi.restoreAllMocks();
  });
});
