-- =====================================================================
-- Baseline schema for the Java migration of the COBOL portfolio system.
-- Sources:
--   VSAM PORTMSTR  -> PORTFOLIO          (copybook PORTFLIO.cpy)
--   VSAM POSFILE   -> POSITION_RECORD    (copybook POSREC.cpy)
--   VSAM TRANFILE  -> TRANSACTION_RECORD (copybook TRNREC.cpy)
--   VSAM TRANHIST  -> HISTORY_RECORD     (copybook HISTREC.cpy)
--   AUDFILE        -> AUDIT_LOG          (copybook AUDITLOG.cpy)
--   DB2 POSHIST    -> POSHIST            (POSHIST.sql / DBTBLS.cpy)
--   DB2 ERRLOG     -> ERRLOG             (ERRLOG.sql / DBTBLS.cpy)
--   DB2 RTNCODES   -> RTNCODES           (RTNCODES.sql)
-- DB2 physical clauses (TABLESPACE, STOGROUP, PARTITION, GRANT, COMMENT,
-- BIND PLAN) have no H2 equivalent and are omitted.
-- =====================================================================

CREATE TABLE PORTFOLIO (
    PORT_ID          VARCHAR(8)        NOT NULL,
    ACCOUNT_NO       VARCHAR(10)       NOT NULL,
    CLIENT_NAME      VARCHAR(30)    NOT NULL,
    CLIENT_TYPE      VARCHAR(1)        NOT NULL,
    CREATE_DATE      DATE,
    LAST_MAINT       DATE,
    STATUS           VARCHAR(1)        NOT NULL,
    TOTAL_VALUE      DECIMAL(15,2)  NOT NULL DEFAULT 0,
    CASH_BALANCE     DECIMAL(15,2)  NOT NULL DEFAULT 0,
    LAST_USER        VARCHAR(8),
    LAST_TRANS       DATE,
    PRIMARY KEY (PORT_ID, ACCOUNT_NO)
);
CREATE INDEX IDX_PORTFOLIO_ACCOUNT ON PORTFOLIO (ACCOUNT_NO);

CREATE TABLE POSITION_RECORD (
    PORTFOLIO_ID     VARCHAR(8)        NOT NULL,
    POSITION_DATE    DATE           NOT NULL,
    INVESTMENT_ID    VARCHAR(10)    NOT NULL,
    QUANTITY         DECIMAL(15,4)  NOT NULL DEFAULT 0,
    COST_BASIS       DECIMAL(15,2)  NOT NULL DEFAULT 0,
    MARKET_VALUE     DECIMAL(15,2)  NOT NULL DEFAULT 0,
    PREVIOUS_VALUE   DECIMAL(15,2),
    DESCRIPTION      VARCHAR(30),
    CURRENCY         VARCHAR(3)        NOT NULL,
    STATUS           VARCHAR(1)        NOT NULL,
    LAST_MAINT_DATE  TIMESTAMP,
    LAST_MAINT_USER  VARCHAR(8),
    PRIMARY KEY (PORTFOLIO_ID, POSITION_DATE, INVESTMENT_ID)
);
CREATE INDEX IDX_POSITION_PORT_INV ON POSITION_RECORD (PORTFOLIO_ID, INVESTMENT_ID, POSITION_DATE);

CREATE TABLE TRANSACTION_RECORD (
    TRN_DATE         DATE           NOT NULL,
    TRN_TIME         TIME           NOT NULL,
    PORTFOLIO_ID     VARCHAR(8)        NOT NULL,
    SEQUENCE_NO      VARCHAR(6)        NOT NULL,
    INVESTMENT_ID    VARCHAR(10)    NOT NULL,
    TRN_TYPE         VARCHAR(2)        NOT NULL,
    QUANTITY         DECIMAL(15,4)  NOT NULL DEFAULT 0,
    PRICE            DECIMAL(15,4)  NOT NULL DEFAULT 0,
    AMOUNT           DECIMAL(15,2)  NOT NULL DEFAULT 0,
    CURRENCY         VARCHAR(3)        NOT NULL,
    STATUS           VARCHAR(1)        NOT NULL,
    PROCESS_DATE     TIMESTAMP,
    PROCESS_USER     VARCHAR(8),
    PRIMARY KEY (TRN_DATE, TRN_TIME, PORTFOLIO_ID, SEQUENCE_NO)
);
CREATE INDEX IDX_TRANSACTION_PORT ON TRANSACTION_RECORD (PORTFOLIO_ID, TRN_DATE);
CREATE INDEX IDX_TRANSACTION_STATUS ON TRANSACTION_RECORD (STATUS);

CREATE TABLE HISTORY_RECORD (
    PORTFOLIO_ID     VARCHAR(8)        NOT NULL,
    HIST_DATE        DATE           NOT NULL,
    HIST_TIME        TIME           NOT NULL,
    SEQ_NO           VARCHAR(4)        NOT NULL,
    RECORD_TYPE      VARCHAR(2)        NOT NULL,
    ACTION_CODE      VARCHAR(1)        NOT NULL,
    BEFORE_IMAGE     CLOB,
    AFTER_IMAGE      CLOB,
    REASON_CODE      VARCHAR(4),
    PROCESS_DATE     TIMESTAMP,
    PROCESS_USER     VARCHAR(8),
    PRIMARY KEY (PORTFOLIO_ID, HIST_DATE, HIST_TIME, SEQ_NO)
);

CREATE TABLE AUDIT_LOG (
    AUDIT_ID         BIGINT         GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    AUD_TIMESTAMP    TIMESTAMP      NOT NULL,
    SYSTEM_ID        VARCHAR(8),
    USER_ID          VARCHAR(8),
    PROGRAM          VARCHAR(8),
    TERMINAL         VARCHAR(8),
    AUD_TYPE         VARCHAR(4)        NOT NULL,
    AUD_ACTION       VARCHAR(8)     NOT NULL,
    AUD_STATUS       VARCHAR(4)        NOT NULL,
    PORTFOLIO_ID     VARCHAR(8),
    ACCOUNT_NO       VARCHAR(10),
    BEFORE_IMAGE     VARCHAR(100),
    AFTER_IMAGE      VARCHAR(100),
    MESSAGE          VARCHAR(100)
);
CREATE INDEX IDX_AUDIT_TS ON AUDIT_LOG (AUD_TIMESTAMP);

-- POSHIST.sql. ACCOUNT_NO widened from VARCHAR(8) to VARCHAR(10) so that the
-- 10-character PORT-ACCOUNT-NO fits without truncation.
-- QUANTITY / PRICE are DECIMAL(15,3): PH-QUANTITY / PH-PRICE PIC S9(12)V9(3).
CREATE TABLE POSHIST (
    ACCOUNT_NO       VARCHAR(10)       NOT NULL,
    PORTFOLIO_ID     VARCHAR(10)       NOT NULL,
    TRANS_DATE       DATE           NOT NULL,
    TRANS_TIME       TIME           NOT NULL,
    TRANS_TYPE       VARCHAR(2)        NOT NULL,
    SECURITY_ID      VARCHAR(12)       NOT NULL,
    QUANTITY         DECIMAL(15,3)  NOT NULL,
    PRICE            DECIMAL(15,3)  NOT NULL,
    AMOUNT           DECIMAL(15,2)  NOT NULL,
    FEES             DECIMAL(15,2)  NOT NULL DEFAULT 0,
    TOTAL_AMOUNT     DECIMAL(15,2)  NOT NULL,
    COST_BASIS       DECIMAL(15,2)  NOT NULL,
    GAIN_LOSS        DECIMAL(15,2)  NOT NULL,
    PROCESS_DATE     DATE           NOT NULL,
    PROCESS_TIME     TIME           NOT NULL,
    PROGRAM_ID       VARCHAR(8)        NOT NULL,
    USER_ID          VARCHAR(8)        NOT NULL,
    AUDIT_TIMESTAMP  TIMESTAMP      NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (ACCOUNT_NO, PORTFOLIO_ID, TRANS_DATE, TRANS_TIME)
);
CREATE INDEX POSHIST_IX1 ON POSHIST (SECURITY_ID, TRANS_DATE);
CREATE INDEX POSHIST_IX2 ON POSHIST (PROCESS_DATE, PROGRAM_ID);

-- ERRLOG.sql
CREATE TABLE ERRLOG (
    ERROR_TIMESTAMP  TIMESTAMP      NOT NULL,
    PROGRAM_ID       VARCHAR(8)        NOT NULL,
    ERROR_TYPE       VARCHAR(1)        NOT NULL,
    ERROR_SEVERITY   INTEGER        NOT NULL,
    ERROR_CODE       VARCHAR(8)        NOT NULL,
    ERROR_MESSAGE    VARCHAR(200)   NOT NULL,
    PROCESS_DATE     DATE           NOT NULL,
    PROCESS_TIME     TIME           NOT NULL,
    USER_ID          VARCHAR(8)        NOT NULL,
    ADDITIONAL_INFO  VARCHAR(500),
    PRIMARY KEY (ERROR_TIMESTAMP, PROGRAM_ID)
);
CREATE INDEX ERRLOG_IX1 ON ERRLOG (PROCESS_DATE, ERROR_SEVERITY DESC);

-- RTNCODES.sql ("TIMESTAMP" column renamed to LOG_TIMESTAMP: reserved word in H2)
CREATE TABLE RTNCODES (
    LOG_TIMESTAMP    TIMESTAMP      NOT NULL,
    PROGRAM_ID       VARCHAR(8)        NOT NULL,
    RETURN_CODE      INTEGER        NOT NULL,
    HIGHEST_CODE     INTEGER        NOT NULL,
    STATUS_CODE      VARCHAR(1)        NOT NULL,
    MESSAGE_TEXT     VARCHAR(80),
    PRIMARY KEY (LOG_TIMESTAMP, PROGRAM_ID)
);
CREATE INDEX RTNCODES_PRG_IDX ON RTNCODES (PROGRAM_ID, LOG_TIMESTAMP);
CREATE INDEX RTNCODES_STS_IDX ON RTNCODES (STATUS_CODE, LOG_TIMESTAMP);
