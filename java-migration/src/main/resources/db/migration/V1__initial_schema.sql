-- ==========================================================================
-- V1: Initial schema for Investment Portfolio Management System
-- Adapted from COBOL DB2 definitions:
--   - src/database/db2/db2-definitions.sql  (PORTFOLIO_MASTER, INVESTMENT_POSITIONS, TRANSACTION_HISTORY)
--   - src/database/db2/POSHIST.sql          (POSHIST)
--   - src/database/db2/ERRLOG.sql           (ERRLOG)
-- DB2-specific syntax (tablespace, stogroup, COMP-3) removed for standard SQL.
-- ==========================================================================

-- PORTFOLIO_MASTER (from PORTFLIO.cpy + db2-definitions.sql)
CREATE TABLE PORTFOLIO_MASTER (
    PORTFOLIO_ID      CHAR(8)         NOT NULL,
    ACCOUNT_TYPE      VARCHAR(2)      NOT NULL,
    BRANCH_ID         CHAR(2)         NOT NULL,
    CLIENT_ID         CHAR(10)        NOT NULL,
    PORTFOLIO_NAME    VARCHAR(50)     NOT NULL,
    CURRENCY_CODE     CHAR(3)         NOT NULL,
    RISK_LEVEL        VARCHAR(1)      NOT NULL,
    STATUS            VARCHAR(1)      NOT NULL,
    TOTAL_VALUE       DECIMAL(15,2),
    CASH_BALANCE      DECIMAL(15,2),
    OPEN_DATE         DATE            NOT NULL,
    CLOSE_DATE        DATE,
    LAST_MAINT_DATE   TIMESTAMP       NOT NULL,
    LAST_MAINT_USER   VARCHAR(8)      NOT NULL,
    PRIMARY KEY (PORTFOLIO_ID)
);

CREATE INDEX IDX_PORT_MASTER_CLIENT ON PORTFOLIO_MASTER (CLIENT_ID, STATUS);

-- INVESTMENT_POSITIONS (from POSREC.cpy + db2-definitions.sql)
CREATE TABLE INVESTMENT_POSITIONS (
    PORTFOLIO_ID      CHAR(8)         NOT NULL,
    INVESTMENT_ID     CHAR(10)        NOT NULL,
    POSITION_DATE     DATE            NOT NULL,
    QUANTITY          DECIMAL(18,4)   NOT NULL,
    COST_BASIS        DECIMAL(18,2)   NOT NULL,
    MARKET_VALUE      DECIMAL(18,2)   NOT NULL,
    CURRENCY_CODE     CHAR(3)         NOT NULL,
    STATUS            VARCHAR(1),
    LAST_MAINT_DATE   TIMESTAMP       NOT NULL,
    LAST_MAINT_USER   VARCHAR(8)      NOT NULL,
    PRIMARY KEY (PORTFOLIO_ID, INVESTMENT_ID, POSITION_DATE),
    FOREIGN KEY (PORTFOLIO_ID) REFERENCES PORTFOLIO_MASTER(PORTFOLIO_ID)
);

CREATE INDEX IDX_POSITIONS_DATE ON INVESTMENT_POSITIONS (POSITION_DATE, PORTFOLIO_ID);

-- TRANSACTION_HISTORY (from TRNREC.cpy + db2-definitions.sql)
CREATE TABLE TRANSACTION_HISTORY (
    TRANSACTION_ID    CHAR(20)        NOT NULL,
    PORTFOLIO_ID      CHAR(8)         NOT NULL,
    TRANSACTION_DATE  DATE            NOT NULL,
    TRANSACTION_TIME  TIME            NOT NULL,
    INVESTMENT_ID     CHAR(10)        NOT NULL,
    TRANSACTION_TYPE  VARCHAR(2)      NOT NULL,
    QUANTITY          DECIMAL(18,4)   NOT NULL,
    PRICE             DECIMAL(18,4)   NOT NULL,
    AMOUNT            DECIMAL(18,2)   NOT NULL,
    CURRENCY_CODE     CHAR(3)         NOT NULL,
    STATUS            VARCHAR(1)      NOT NULL,
    PROCESS_DATE      TIMESTAMP       NOT NULL,
    PROCESS_USER      VARCHAR(8)      NOT NULL,
    PRIMARY KEY (TRANSACTION_ID),
    FOREIGN KEY (PORTFOLIO_ID) REFERENCES PORTFOLIO_MASTER(PORTFOLIO_ID)
);

CREATE INDEX IDX_TRANS_HIST_PORT ON TRANSACTION_HISTORY (PORTFOLIO_ID, TRANSACTION_DATE);
CREATE INDEX IDX_TRANS_HIST_DATE ON TRANSACTION_HISTORY (TRANSACTION_DATE, PORTFOLIO_ID);

-- POSHIST (from src/database/db2/POSHIST.sql)
CREATE TABLE POSHIST (
    ID                BIGINT          GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    ACCOUNT_NO        CHAR(8)         NOT NULL,
    PORTFOLIO_ID      CHAR(10)        NOT NULL,
    TRANS_DATE        DATE            NOT NULL,
    TRANS_TIME        TIME            NOT NULL,
    TRANS_TYPE        CHAR(2)         NOT NULL,
    SECURITY_ID       CHAR(12)        NOT NULL,
    QUANTITY          DECIMAL(15,3)   NOT NULL,
    PRICE             DECIMAL(15,3)   NOT NULL,
    AMOUNT            DECIMAL(15,2)   NOT NULL,
    FEES              DECIMAL(15,2)   NOT NULL DEFAULT 0,
    TOTAL_AMOUNT      DECIMAL(15,2)   NOT NULL,
    COST_BASIS        DECIMAL(15,2)   NOT NULL,
    GAIN_LOSS         DECIMAL(15,2)   NOT NULL,
    PROCESS_DATE      DATE            NOT NULL,
    PROCESS_TIME      TIME            NOT NULL,
    PROGRAM_ID        CHAR(8)         NOT NULL,
    USER_ID           CHAR(8)         NOT NULL,
    AUDIT_TIMESTAMP   TIMESTAMP       DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX POSHIST_IX1 ON POSHIST (SECURITY_ID, TRANS_DATE);
CREATE INDEX POSHIST_IX2 ON POSHIST (PROCESS_DATE, PROGRAM_ID);

-- AUDIT_LOG (from AUDITLOG.cpy — no explicit DDL in COBOL source)
CREATE TABLE AUDIT_LOG (
    ID                BIGINT          GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    AUDIT_TIMESTAMP   TIMESTAMP       NOT NULL,
    SYSTEM_ID         VARCHAR(8),
    USER_ID           VARCHAR(8),
    PROGRAM           VARCHAR(8),
    TERMINAL          VARCHAR(8),
    AUDIT_TYPE        VARCHAR(4)      NOT NULL,
    AUDIT_ACTION      VARCHAR(8)      NOT NULL,
    STATUS            VARCHAR(4),
    PORTFOLIO_ID      VARCHAR(8),
    ACCOUNT_NO        VARCHAR(10),
    BEFORE_IMAGE      TEXT,
    AFTER_IMAGE       TEXT,
    MESSAGE           VARCHAR(100)
);

CREATE INDEX IDX_AUDIT_LOG_PORT ON AUDIT_LOG (PORTFOLIO_ID, AUDIT_TIMESTAMP);
CREATE INDEX IDX_AUDIT_LOG_TYPE ON AUDIT_LOG (AUDIT_TYPE, AUDIT_TIMESTAMP);

-- ERROR_LOG (from src/database/db2/ERRLOG.sql)
CREATE TABLE ERROR_LOG (
    ERROR_TIMESTAMP   TIMESTAMP       NOT NULL,
    PROGRAM_ID        CHAR(8)         NOT NULL,
    ERROR_TYPE        CHAR(1)         NOT NULL,
    ERROR_SEVERITY    INTEGER         NOT NULL,
    ERROR_CODE        CHAR(8)         NOT NULL,
    ERROR_MESSAGE     VARCHAR(200)    NOT NULL,
    PROCESS_DATE      DATE            NOT NULL,
    PROCESS_TIME      TIME            NOT NULL,
    USER_ID           CHAR(8)         NOT NULL,
    ADDITIONAL_INFO   VARCHAR(500),
    PRIMARY KEY (ERROR_TIMESTAMP, PROGRAM_ID)
);

CREATE INDEX IDX_ERRLOG_DATE ON ERROR_LOG (PROCESS_DATE, ERROR_SEVERITY);

-- VIEWS (from db2-definitions.sql, adapted for standard SQL)
CREATE VIEW ACTIVE_PORTFOLIOS AS
    SELECT *
    FROM PORTFOLIO_MASTER
    WHERE STATUS = 'A'
    AND (CLOSE_DATE IS NULL OR CLOSE_DATE > CURRENT_DATE);
