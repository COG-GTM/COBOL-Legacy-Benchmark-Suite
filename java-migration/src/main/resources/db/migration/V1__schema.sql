CREATE TABLE PORTFOLIO_MASTER (
    PORTFOLIO_ID CHAR(8) PRIMARY KEY, ACCOUNT_NO CHAR(10) NOT NULL, CLIENT_NAME VARCHAR(30) NOT NULL,
    CLIENT_TYPE CHAR(1) NOT NULL, CREATE_DATE DATE NOT NULL, LAST_MAINT_DATE DATE, STATUS CHAR(1) NOT NULL,
    TOTAL_VALUE DECIMAL(18,2) NOT NULL DEFAULT 0, CASH_BALANCE DECIMAL(18,2) NOT NULL DEFAULT 0,
    TOTAL_UNITS DECIMAL(18,4) NOT NULL DEFAULT 0, TOTAL_COST DECIMAL(18,2) NOT NULL DEFAULT 0,
    LAST_USER VARCHAR(8), LAST_TRANS_DATE DATE, ACCOUNT_TYPE CHAR(2), BRANCH_ID CHAR(2),
    CURRENCY_CODE CHAR(3) NOT NULL DEFAULT 'USD', RISK_LEVEL CHAR(1), CLOSE_DATE DATE
);
CREATE UNIQUE INDEX IDX_PORTFOLIO_ACCOUNT ON PORTFOLIO_MASTER(ACCOUNT_NO);
CREATE INDEX IDX_PORTFOLIO_STATUS ON PORTFOLIO_MASTER(STATUS);

CREATE TABLE INVESTMENT_POSITIONS (
    PORTFOLIO_ID CHAR(8) NOT NULL, INVESTMENT_ID CHAR(10) NOT NULL, POSITION_DATE DATE NOT NULL,
    QUANTITY DECIMAL(18,4), COST_BASIS DECIMAL(18,2), MARKET_VALUE DECIMAL(18,2), CURRENCY_CODE CHAR(3),
    STATUS CHAR(1) NOT NULL DEFAULT 'A', LAST_MAINT_DATE TIMESTAMP, LAST_MAINT_USER VARCHAR(8),
    PRIMARY KEY(PORTFOLIO_ID, INVESTMENT_ID, POSITION_DATE),
    FOREIGN KEY(PORTFOLIO_ID) REFERENCES PORTFOLIO_MASTER(PORTFOLIO_ID)
);

CREATE TABLE TRANSACTION_HISTORY (
    TRANSACTION_ID VARCHAR(28) PRIMARY KEY, TRANSACTION_DATE DATE, TRANSACTION_TIME TIME,
    PORTFOLIO_ID CHAR(8), SEQUENCE_NO CHAR(6), INVESTMENT_ID CHAR(10), TRANSACTION_TYPE CHAR(2),
    QUANTITY DECIMAL(18,4), PRICE DECIMAL(18,4), AMOUNT DECIMAL(18,2), CURRENCY_CODE CHAR(3),
    STATUS CHAR(1), PROCESS_DATE TIMESTAMP, PROCESS_USER VARCHAR(8),
    FOREIGN KEY(PORTFOLIO_ID) REFERENCES PORTFOLIO_MASTER(PORTFOLIO_ID)
);
CREATE INDEX IDX_TRANS_PORT_DATE ON TRANSACTION_HISTORY(PORTFOLIO_ID, TRANSACTION_DATE);
CREATE INDEX IDX_TRANS_DATE_PORT ON TRANSACTION_HISTORY(TRANSACTION_DATE, PORTFOLIO_ID);

CREATE TABLE HISTORY_RECORD (
    PORTFOLIO_ID CHAR(8) NOT NULL, HIST_DATE CHAR(8) NOT NULL, HIST_TIME CHAR(6) NOT NULL,
    SEQ_NO CHAR(4) NOT NULL, RECORD_TYPE CHAR(2), ACTION_CODE CHAR(1), BEFORE_IMAGE CLOB,
    AFTER_IMAGE CLOB, REASON_CODE CHAR(4), PROCESS_DATE TIMESTAMP, PROCESS_USER VARCHAR(8),
    PRIMARY KEY(PORTFOLIO_ID, HIST_DATE, HIST_TIME, SEQ_NO)
);

-- POSHIST ACCOUNT_NO is CHAR(10), widened from the original CHAR(8) to match portfolio copybooks.
CREATE TABLE POSHIST (
    ACCOUNT_NO CHAR(10) NOT NULL, PORTFOLIO_ID CHAR(10) NOT NULL, TRANS_DATE DATE NOT NULL,
    TRANS_TIME TIME NOT NULL, TRANS_TYPE CHAR(2) NOT NULL, SECURITY_ID CHAR(12) NOT NULL,
    QUANTITY DECIMAL(15,3) NOT NULL, PRICE DECIMAL(15,3) NOT NULL, AMOUNT DECIMAL(15,2) NOT NULL,
    FEES DECIMAL(15,2) NOT NULL DEFAULT 0, TOTAL_AMOUNT DECIMAL(15,2) NOT NULL,
    COST_BASIS DECIMAL(15,2) NOT NULL, GAIN_LOSS DECIMAL(15,2) NOT NULL, PROCESS_DATE DATE NOT NULL,
    PROCESS_TIME TIME NOT NULL, PROGRAM_ID CHAR(8) NOT NULL, USER_ID CHAR(8) NOT NULL,
    AUDIT_TIMESTAMP TIMESTAMP NOT NULL, PRIMARY KEY(ACCOUNT_NO, PORTFOLIO_ID, TRANS_DATE, TRANS_TIME)
);
CREATE INDEX POSHIST_IX1 ON POSHIST(SECURITY_ID, TRANS_DATE);
CREATE INDEX POSHIST_IX2 ON POSHIST(PROCESS_DATE, PROGRAM_ID);

CREATE TABLE ERRLOG (
    ERRLOG_ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, ERROR_TIMESTAMP TIMESTAMP NOT NULL,
    PROGRAM_ID CHAR(8) NOT NULL, ERROR_TYPE CHAR(1) NOT NULL, ERROR_SEVERITY INTEGER NOT NULL,
    ERROR_CODE CHAR(8) NOT NULL, ERROR_MESSAGE VARCHAR(200) NOT NULL, PROCESS_DATE DATE NOT NULL,
    PROCESS_TIME TIME NOT NULL, USER_ID CHAR(8) NOT NULL, ADDITIONAL_INFO VARCHAR(500)
);
CREATE INDEX ERRLOG_IX1 ON ERRLOG(PROCESS_DATE, ERROR_SEVERITY);

CREATE TABLE AUDITLOG (
    AUDIT_ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, AUD_TIMESTAMP TIMESTAMP,
    SYSTEM_ID CHAR(8), USER_ID CHAR(8), PROGRAM CHAR(8), TERMINAL CHAR(8), AUD_TYPE CHAR(4),
    ACTION CHAR(8), STATUS CHAR(4), PORTFOLIO_ID CHAR(8), ACCOUNT_NO CHAR(10),
    BEFORE_IMAGE VARCHAR(100), AFTER_IMAGE VARCHAR(100), MESSAGE VARCHAR(100), TRANS_ID CHAR(4),
    ACCESS_TYPE CHAR(8)
);

CREATE TABLE AUTHFILE (
    AUTH_ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, USER_ID VARCHAR(8) NOT NULL,
    RESOURCE_NAME VARCHAR(8) NOT NULL, ACCESS_TYPE VARCHAR(8) NOT NULL,
    CONSTRAINT AUTHFILE_UQ UNIQUE(USER_ID, RESOURCE_NAME, ACCESS_TYPE)
);

CREATE TABLE APP_USER (
    USER_ID VARCHAR(8) PRIMARY KEY, PASSWORD_HASH VARCHAR(100) NOT NULL, ROLE VARCHAR(16) NOT NULL,
    ENABLED BOOLEAN NOT NULL
);

CREATE TABLE RTNCODES (
    RTN_ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, RC_TIMESTAMP TIMESTAMP NOT NULL,
    PROGRAM_ID CHAR(8) NOT NULL, RETURN_CODE INTEGER NOT NULL, HIGHEST_CODE INTEGER NOT NULL,
    STATUS_CODE CHAR(1) NOT NULL, MESSAGE_TEXT VARCHAR(80)
);
