-- Audit Log Table (from AUDITLOG.cpy)
CREATE TABLE audit_log (
    id                BIGINT          GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    audit_timestamp   TIMESTAMP       NOT NULL DEFAULT CURRENT_TIMESTAMP,
    system_id         VARCHAR(8)      NOT NULL,
    user_id           VARCHAR(8)      NOT NULL,
    program           VARCHAR(8)      NOT NULL,
    terminal          VARCHAR(8),
    audit_type        VARCHAR(4)      NOT NULL,
    action            VARCHAR(8)      NOT NULL,
    status            VARCHAR(4)      NOT NULL,
    portfolio_id      VARCHAR(8),
    account_no        VARCHAR(10),
    before_image      VARCHAR(100),
    after_image       VARCHAR(100),
    message           VARCHAR(100)
);

-- History Records Table (from HISTREC.cpy)
CREATE TABLE history_record (
    id                BIGINT          GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    portfolio_id      VARCHAR(8)         NOT NULL,
    history_date      DATE            NOT NULL,
    history_time      VARCHAR(6)      NOT NULL,
    seq_no            VARCHAR(4)      NOT NULL,
    record_type       VARCHAR(2)         NOT NULL,
    action_code       VARCHAR(1)         NOT NULL,
    before_image      VARCHAR(400),
    after_image       VARCHAR(400),
    reason_code       VARCHAR(4),
    process_date      TIMESTAMP       NOT NULL DEFAULT CURRENT_TIMESTAMP,
    process_user      VARCHAR(8)      NOT NULL,
    filler            VARCHAR(50)
);

-- Batch Control Table (from BCHCTL.cpy)
CREATE TABLE batch_control (
    job_name          VARCHAR(8)      NOT NULL,
    process_date      DATE            NOT NULL,
    sequence_no       INTEGER         NOT NULL,
    status            VARCHAR(1)      NOT NULL DEFAULT 'R',
    step_name         VARCHAR(8),
    program_name      VARCHAR(8),
    start_time        VARCHAR(8),
    end_time          VARCHAR(8),
    prereq_count      INTEGER         DEFAULT 0,
    return_code       INTEGER         DEFAULT 0,
    error_desc        VARCHAR(80),
    restart_count     INTEGER         DEFAULT 0,
    attempt_ts        TIMESTAMP,
    complete_ts       TIMESTAMP,
    PRIMARY KEY (job_name, process_date, sequence_no)
);

