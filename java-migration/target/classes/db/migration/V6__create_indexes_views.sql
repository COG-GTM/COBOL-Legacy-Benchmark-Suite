-- Views from db2-definitions.sql
-- ACTIVE_PORTFOLIOS: CURRENT DATE adapted from DB2 syntax
CREATE VIEW active_portfolios AS
    SELECT *
    FROM portfolio_master
    WHERE status = 'A'
    AND (close_date IS NULL OR close_date > CURRENT_DATE);

-- CURRENT_POSITIONS: CURRENT DATE - 1 DAY adapted from DB2 syntax
CREATE VIEW current_positions AS
    SELECT p.*, pm.client_id
    FROM investment_positions p
    JOIN portfolio_master pm ON p.portfolio_id = pm.portfolio_id
    WHERE p.position_date = CURRENT_DATE - 1;
