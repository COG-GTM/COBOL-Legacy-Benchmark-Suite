-- Source: src/database/db2/db2-definitions.sql
-- DB2-only clauses (database/tablespace placement, GRANTs) are omitted. CHAR(n) columns become
-- VARCHAR(n): the Java record layer strips COBOL space padding, so fixed-width padding is not
-- reproduced in the database. All widths, precisions and scales match the DB2 DDL.

CREATE TABLE PORTFOLIO_MASTER (
    PORTFOLIO_ID      VARCHAR(8)      NOT NULL,
    ACCOUNT_TYPE      VARCHAR(2)      NOT NULL,
    BRANCH_ID         VARCHAR(2)      NOT NULL,
    CLIENT_ID         VARCHAR(10)     NOT NULL,
    PORTFOLIO_NAME    VARCHAR(50)     NOT NULL,
    CURRENCY_CODE     VARCHAR(3)      NOT NULL,
    RISK_LEVEL        VARCHAR(1)      NOT NULL,
    STATUS            VARCHAR(1)      NOT NULL,
    OPEN_DATE         DATE            NOT NULL,
    CLOSE_DATE        DATE,
    LAST_MAINT_DATE   TIMESTAMP(6)    NOT NULL,
    LAST_MAINT_USER   VARCHAR(8)      NOT NULL,
    CONSTRAINT PK_PORTFOLIO_MASTER PRIMARY KEY (PORTFOLIO_ID)
);

CREATE TABLE INVESTMENT_POSITIONS (
    PORTFOLIO_ID      VARCHAR(8)      NOT NULL,
    INVESTMENT_ID     VARCHAR(10)     NOT NULL,
    POSITION_DATE     DATE            NOT NULL,
    QUANTITY          DECIMAL(18,4)   NOT NULL,
    COST_BASIS        DECIMAL(18,2)   NOT NULL,
    MARKET_VALUE      DECIMAL(18,2)   NOT NULL,
    CURRENCY_CODE     VARCHAR(3)      NOT NULL,
    LAST_MAINT_DATE   TIMESTAMP(6)    NOT NULL,
    LAST_MAINT_USER   VARCHAR(8)      NOT NULL,
    CONSTRAINT PK_INVESTMENT_POSITIONS PRIMARY KEY (PORTFOLIO_ID, INVESTMENT_ID, POSITION_DATE),
    CONSTRAINT FK_POSITIONS_PORTFOLIO FOREIGN KEY (PORTFOLIO_ID)
        REFERENCES PORTFOLIO_MASTER (PORTFOLIO_ID)
);

CREATE TABLE TRANSACTION_HISTORY (
    TRANSACTION_ID    VARCHAR(20)     NOT NULL,
    PORTFOLIO_ID      VARCHAR(8)      NOT NULL,
    TRANSACTION_DATE  DATE            NOT NULL,
    TRANSACTION_TIME  TIME            NOT NULL,
    INVESTMENT_ID     VARCHAR(10)     NOT NULL,
    TRANSACTION_TYPE  VARCHAR(2)      NOT NULL,
    QUANTITY          DECIMAL(18,4)   NOT NULL,
    PRICE             DECIMAL(18,4)   NOT NULL,
    AMOUNT            DECIMAL(18,2)   NOT NULL,
    CURRENCY_CODE     VARCHAR(3)      NOT NULL,
    STATUS            VARCHAR(1)      NOT NULL,
    PROCESS_DATE      TIMESTAMP(6)    NOT NULL,
    PROCESS_USER      VARCHAR(8)      NOT NULL,
    CONSTRAINT PK_TRANSACTION_HISTORY PRIMARY KEY (TRANSACTION_ID),
    CONSTRAINT FK_TRANS_HIST_PORTFOLIO FOREIGN KEY (PORTFOLIO_ID)
        REFERENCES PORTFOLIO_MASTER (PORTFOLIO_ID)
);

CREATE INDEX IDX_PORT_MASTER_CLIENT ON PORTFOLIO_MASTER (CLIENT_ID, STATUS);
CREATE INDEX IDX_POSITIONS_DATE ON INVESTMENT_POSITIONS (POSITION_DATE, PORTFOLIO_ID);
CREATE INDEX IDX_TRANS_HIST_PORT ON TRANSACTION_HISTORY (PORTFOLIO_ID, TRANSACTION_DATE);
CREATE INDEX IDX_TRANS_HIST_DATE ON TRANSACTION_HISTORY (TRANSACTION_DATE, PORTFOLIO_ID);

-- DB2 "CURRENT DATE" / "CURRENT DATE - 1 DAY" rewritten in standard SQL.
CREATE VIEW ACTIVE_PORTFOLIOS AS
    SELECT *
    FROM PORTFOLIO_MASTER
    WHERE STATUS = 'A'
    AND (CLOSE_DATE IS NULL OR CLOSE_DATE > CURRENT_DATE);

CREATE VIEW CURRENT_POSITIONS AS
    SELECT p.*, pm.PORTFOLIO_NAME, pm.CLIENT_ID
    FROM INVESTMENT_POSITIONS p
    JOIN PORTFOLIO_MASTER pm ON p.PORTFOLIO_ID = pm.PORTFOLIO_ID
    WHERE p.POSITION_DATE = CURRENT_DATE - INTERVAL '1' DAY;
