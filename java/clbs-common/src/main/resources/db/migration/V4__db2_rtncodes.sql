-- The DB2 column named TIMESTAMP is renamed LOG_TIMESTAMP to avoid the SQL reserved word.

CREATE TABLE RTNCODES (
    LOG_TIMESTAMP     TIMESTAMP(6)    NOT NULL,
    PROGRAM_ID        VARCHAR(8)      NOT NULL,
    RETURN_CODE       INTEGER         NOT NULL,
    HIGHEST_CODE      INTEGER         NOT NULL,
    STATUS_CODE       VARCHAR(1)      NOT NULL,
    MESSAGE_TEXT      VARCHAR(80),
    CONSTRAINT PK_RTNCODES PRIMARY KEY (LOG_TIMESTAMP, PROGRAM_ID)
);

CREATE INDEX RTNCODES_PRG_IDX ON RTNCODES (PROGRAM_ID, LOG_TIMESTAMP);
CREATE INDEX RTNCODES_STS_IDX ON RTNCODES (STATUS_CODE, LOG_TIMESTAMP);
