-- Relational equivalents of the VSAM KSDS files (src/database/vsam/vsam-definitions.txt), one table
-- per record copybook. Column widths mirror the PICTURE clauses; COMP-3 fields become DECIMAL with
-- the copybook digit count and scale; YYYYMMDD / HHMMSS / DB2 timestamp text becomes DATE / TIME /
-- TIMESTAMP. The KSDS key is the primary key. FILLER is not stored.

-- PORTFILE: src/copybook/common/PORTFLIO.cpy (PORT-RECORD, 148 bytes, key PORT-ID + PORT-ACCOUNT-NO)
CREATE TABLE PORTFOLIO (
    PORTFOLIO_ID      VARCHAR(8)      NOT NULL,
    ACCOUNT_NO        VARCHAR(10)     NOT NULL,
    CLIENT_NAME       VARCHAR(30)     NOT NULL,
    CLIENT_TYPE       VARCHAR(1)      NOT NULL,
    CREATE_DATE       DATE,
    LAST_MAINT_DATE   DATE,
    STATUS            VARCHAR(1)      NOT NULL,
    TOTAL_VALUE       DECIMAL(15,2)   NOT NULL,
    CASH_BALANCE      DECIMAL(15,2)   NOT NULL,
    LAST_USER         VARCHAR(8),
    LAST_TRANS_DATE   DATE,
    CONSTRAINT PK_PORTFOLIO PRIMARY KEY (PORTFOLIO_ID, ACCOUNT_NO)
);

-- Position master: src/copybook/common/POSREC.cpy (POSITION-RECORD, 138 bytes, key POS-KEY)
CREATE TABLE POSITION_MASTER (
    PORTFOLIO_ID         VARCHAR(8)      NOT NULL,
    POSITION_DATE        DATE            NOT NULL,
    INVESTMENT_ID        VARCHAR(10)     NOT NULL,
    QUANTITY             DECIMAL(15,4)   NOT NULL,
    COST_BASIS           DECIMAL(15,2)   NOT NULL,
    MARKET_VALUE         DECIMAL(15,2)   NOT NULL,
    CURRENCY_CODE        VARCHAR(3)      NOT NULL,
    STATUS               VARCHAR(1)      NOT NULL,
    LAST_MAINT_TIMESTAMP TIMESTAMP(6),
    LAST_MAINT_USER      VARCHAR(8),
    CONSTRAINT PK_POSITION_MASTER PRIMARY KEY (PORTFOLIO_ID, POSITION_DATE, INVESTMENT_ID)
);

CREATE INDEX IDX_POSITION_MASTER_INVESTMENT ON POSITION_MASTER (INVESTMENT_ID, POSITION_DATE);

-- TRANFILE: src/copybook/common/TRNREC.cpy (TRANSACTION-RECORD, 152 bytes, key TRN-KEY)
CREATE TABLE PORTFOLIO_TRANSACTION (
    TRANSACTION_DATE  DATE            NOT NULL,
    TRANSACTION_TIME  TIME            NOT NULL,
    PORTFOLIO_ID      VARCHAR(8)      NOT NULL,
    SEQUENCE_NO       VARCHAR(6)      NOT NULL,
    INVESTMENT_ID     VARCHAR(10)     NOT NULL,
    TRANSACTION_TYPE  VARCHAR(2)      NOT NULL,
    QUANTITY          DECIMAL(15,4)   NOT NULL,
    PRICE             DECIMAL(15,4)   NOT NULL,
    AMOUNT            DECIMAL(15,2)   NOT NULL,
    CURRENCY_CODE     VARCHAR(3)      NOT NULL,
    STATUS            VARCHAR(1)      NOT NULL,
    PROCESS_TIMESTAMP TIMESTAMP(6),
    PROCESS_USER      VARCHAR(8),
    CONSTRAINT PK_PORTFOLIO_TRANSACTION
        PRIMARY KEY (TRANSACTION_DATE, TRANSACTION_TIME, PORTFOLIO_ID, SEQUENCE_NO)
);

CREATE INDEX IDX_PORTFOLIO_TRANSACTION_PORT ON PORTFOLIO_TRANSACTION (PORTFOLIO_ID, TRANSACTION_DATE);

-- TRANHIST: src/copybook/common/HISTREC.cpy (HISTORY-RECORD, 917 bytes, key HIST-KEY)
CREATE TABLE CHANGE_HISTORY (
    PORTFOLIO_ID      VARCHAR(8)      NOT NULL,
    HISTORY_DATE      DATE            NOT NULL,
    HISTORY_TIME      TIME            NOT NULL,
    SEQUENCE_NO       VARCHAR(4)      NOT NULL,
    RECORD_TYPE       VARCHAR(2)      NOT NULL,
    ACTION_CODE       VARCHAR(1)      NOT NULL,
    BEFORE_IMAGE      VARCHAR(400),
    AFTER_IMAGE       VARCHAR(400),
    REASON_CODE       VARCHAR(4),
    PROCESS_TIMESTAMP TIMESTAMP(6),
    PROCESS_USER      VARCHAR(8),
    CONSTRAINT PK_CHANGE_HISTORY PRIMARY KEY (PORTFOLIO_ID, HISTORY_DATE, HISTORY_TIME, SEQUENCE_NO)
);
