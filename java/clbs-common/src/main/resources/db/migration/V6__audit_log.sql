-- AUDFILE: src/copybook/common/AUDITLOG.cpy (AUDIT-RECORD, 392 bytes). The sequential audit file has
-- no key, so rows get a surrogate identity; insertion order is preserved by AUDIT_ID.

CREATE TABLE AUDIT_LOG (
    AUDIT_ID          BIGINT          GENERATED BY DEFAULT AS IDENTITY,
    AUDIT_TIMESTAMP   TIMESTAMP(6)    NOT NULL,
    SYSTEM_ID         VARCHAR(8)      NOT NULL,
    USER_ID           VARCHAR(8)      NOT NULL,
    PROGRAM_ID        VARCHAR(8)      NOT NULL,
    TERMINAL_ID       VARCHAR(8),
    AUDIT_TYPE        VARCHAR(4)      NOT NULL,
    AUDIT_ACTION      VARCHAR(8)      NOT NULL,
    AUDIT_STATUS      VARCHAR(4)      NOT NULL,
    PORTFOLIO_ID      VARCHAR(8),
    ACCOUNT_NO        VARCHAR(10),
    BEFORE_IMAGE      VARCHAR(100),
    AFTER_IMAGE       VARCHAR(100),
    MESSAGE_TEXT      VARCHAR(100),
    CONSTRAINT PK_AUDIT_LOG PRIMARY KEY (AUDIT_ID)
);

CREATE INDEX IDX_AUDIT_LOG_PORTFOLIO ON AUDIT_LOG (PORTFOLIO_ID, AUDIT_TIMESTAMP);
CREATE INDEX IDX_AUDIT_LOG_TIMESTAMP ON AUDIT_LOG (AUDIT_TIMESTAMP);
