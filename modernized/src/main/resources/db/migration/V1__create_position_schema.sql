-- =====================================================================
-- V1: Position-update schema
-- Modernized from:
--   VSAM KSDS POSMSTR  (copybook src/copybook/common/POSREC.cpy)  -> position_master
--   Transaction input  (copybook src/copybook/common/TRNREC.cpy)  -> txn
--   DB2 table POSHIST  (src/database/db2/POSHIST.sql)             -> position_history
-- Column types map COBOL PIC clauses to SQL per the migration playbook:
--   PIC X(n)          -> VARCHAR(n)
--   PIC S9(i)V9(d)    -> DECIMAL(i+d, d)  (here normalized to precision 15)
--   PIC X(8) date     -> kept as VARCHAR(8) for VSAM-origin keys (YYYYMMDD)
--   DB2 DATE/TIME/TS  -> DATE / TIME / TIMESTAMP
-- =====================================================================

CREATE TABLE position_master (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    portfolio_id    VARCHAR(8)     NOT NULL,   -- POS-PORTFOLIO-ID PIC X(08)
    position_date   VARCHAR(8)     NOT NULL,   -- POS-DATE         PIC X(08)
    investment_id   VARCHAR(10)    NOT NULL,   -- POS-INVESTMENT-ID PIC X(10)
    quantity        DECIMAL(15,4)  NOT NULL,   -- POS-QUANTITY     PIC S9(11)V9(4)
    cost_basis      DECIMAL(15,2)  NOT NULL,   -- POS-COST-BASIS   PIC S9(13)V9(2)
    market_value    DECIMAL(15,2)  NOT NULL,   -- POS-MARKET-VALUE PIC S9(13)V9(2)
    currency        VARCHAR(3),                 -- POS-CURRENCY     PIC X(03)
    status          VARCHAR(1)     NOT NULL,   -- POS-STATUS       PIC X(01)
    last_maint_date VARCHAR(26),                -- POS-LAST-MAINT-DATE PIC X(26)
    last_maint_user VARCHAR(8),                 -- POS-LAST-MAINT-USER PIC X(08)
    CONSTRAINT uq_position_key UNIQUE (portfolio_id, position_date, investment_id)
);

CREATE TABLE txn (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    trn_date        VARCHAR(8)     NOT NULL,   -- TRN-DATE         PIC X(08)
    trn_time        VARCHAR(6)     NOT NULL,   -- TRN-TIME         PIC X(06)
    portfolio_id    VARCHAR(8)     NOT NULL,   -- TRN-PORTFOLIO-ID PIC X(08)
    sequence_no     VARCHAR(6)     NOT NULL,   -- TRN-SEQUENCE-NO  PIC X(06)
    investment_id   VARCHAR(10)    NOT NULL,   -- TRN-INVESTMENT-ID PIC X(10)
    trn_type        VARCHAR(2)     NOT NULL,   -- TRN-TYPE         PIC X(02)
    quantity        DECIMAL(15,4)  NOT NULL,   -- TRN-QUANTITY     PIC S9(11)V9(4)
    price           DECIMAL(15,4)  NOT NULL,   -- TRN-PRICE        PIC S9(11)V9(4)
    amount          DECIMAL(15,2)  NOT NULL,   -- TRN-AMOUNT       PIC S9(13)V9(2)
    currency        VARCHAR(3),                 -- TRN-CURRENCY     PIC X(03)
    status          VARCHAR(1)     NOT NULL,   -- TRN-STATUS       PIC X(01)
    process_date    VARCHAR(26),                -- TRN-PROCESS-DATE PIC X(26)
    process_user    VARCHAR(8),                 -- TRN-PROCESS-USER PIC X(08)
    CONSTRAINT uq_transaction_key UNIQUE (trn_date, trn_time, portfolio_id, sequence_no)
);

CREATE TABLE position_history (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_no      VARCHAR(8)     NOT NULL,   -- PH-ACCOUNT-NO   CHAR(8)
    portfolio_id    VARCHAR(10)    NOT NULL,   -- PH-PORTFOLIO-ID CHAR(10)
    trans_date      DATE           NOT NULL,   -- TRANS_DATE      DATE
    trans_time      TIME           NOT NULL,   -- TRANS_TIME      TIME
    trans_type      VARCHAR(2)     NOT NULL,   -- TRANS_TYPE      CHAR(2)
    security_id     VARCHAR(12)    NOT NULL,   -- SECURITY_ID     CHAR(12)
    quantity        DECIMAL(15,3)  NOT NULL,   -- QUANTITY        DECIMAL(15,3)
    price           DECIMAL(15,3)  NOT NULL,   -- PRICE           DECIMAL(15,3)
    amount          DECIMAL(15,2)  NOT NULL,   -- AMOUNT          DECIMAL(15,2)
    fees            DECIMAL(15,2)  NOT NULL,   -- FEES            DECIMAL(15,2)
    total_amount    DECIMAL(15,2)  NOT NULL,   -- TOTAL_AMOUNT    DECIMAL(15,2)
    cost_basis      DECIMAL(15,2)  NOT NULL,   -- COST_BASIS      DECIMAL(15,2)
    gain_loss       DECIMAL(15,2)  NOT NULL,   -- GAIN_LOSS       DECIMAL(15,2)
    process_date    DATE           NOT NULL,   -- PROCESS_DATE    DATE
    process_time    TIME           NOT NULL,   -- PROCESS_TIME    TIME
    program_id      VARCHAR(8)     NOT NULL,   -- PROGRAM_ID      CHAR(8)
    user_id         VARCHAR(8)     NOT NULL,   -- USER_ID         CHAR(8)
    audit_timestamp TIMESTAMP      NOT NULL    -- AUDIT_TIMESTAMP TIMESTAMP
);

CREATE INDEX ix_position_portfolio ON position_master (portfolio_id);
CREATE INDEX ix_txn_status ON txn (status);
CREATE INDEX ix_poshist_portfolio_date ON position_history (portfolio_id, trans_date);
CREATE INDEX ix_poshist_security ON position_history (security_id, trans_date);
