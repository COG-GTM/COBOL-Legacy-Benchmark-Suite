-- Portfolio Master Table (from db2-definitions.sql)
CREATE TABLE PORTFOLIO_MASTER (
    PORTFOLIO_ID      CHAR(8)         NOT NULL,
    ACCOUNT_TYPE      CHAR(2)         NOT NULL,
    BRANCH_ID         CHAR(2)         NOT NULL,
    CLIENT_ID         CHAR(10)        NOT NULL,
    PORTFOLIO_NAME    VARCHAR(50)     NOT NULL,
    CURRENCY_CODE     CHAR(3)         NOT NULL,
    RISK_LEVEL        CHAR(1)         NOT NULL,
    STATUS            CHAR(1)         NOT NULL,
    OPEN_DATE         DATE            NOT NULL,
    CLOSE_DATE        DATE,
    LAST_MAINT_DATE   TIMESTAMP       NOT NULL,
    LAST_MAINT_USER   VARCHAR(8)      NOT NULL,
    PRIMARY KEY (PORTFOLIO_ID)
);

-- Investment Positions Table (from db2-definitions.sql)
CREATE TABLE INVESTMENT_POSITIONS (
    PORTFOLIO_ID      CHAR(8)         NOT NULL,
    INVESTMENT_ID     CHAR(10)        NOT NULL,
    POSITION_DATE     DATE            NOT NULL,
    QUANTITY          DECIMAL(18,4)   NOT NULL,
    COST_BASIS        DECIMAL(18,2)   NOT NULL,
    MARKET_VALUE      DECIMAL(18,2)   NOT NULL,
    CURRENCY_CODE     CHAR(3)         NOT NULL,
    STATUS            CHAR(1)         NOT NULL DEFAULT 'A',
    LAST_MAINT_DATE   TIMESTAMP       NOT NULL,
    LAST_MAINT_USER   VARCHAR(8)      NOT NULL,
    PRIMARY KEY (PORTFOLIO_ID, INVESTMENT_ID, POSITION_DATE),
    FOREIGN KEY (PORTFOLIO_ID) REFERENCES PORTFOLIO_MASTER(PORTFOLIO_ID)
);

-- Transaction History Table (from db2-definitions.sql)
CREATE TABLE TRANSACTION_HISTORY (
    TRANSACTION_ID    CHAR(20)        NOT NULL,
    PORTFOLIO_ID      CHAR(8)         NOT NULL,
    TRANSACTION_DATE  DATE            NOT NULL,
    TRANSACTION_TIME  TIME            NOT NULL,
    INVESTMENT_ID     CHAR(10)        NOT NULL,
    TRANSACTION_TYPE  CHAR(2)         NOT NULL,
    QUANTITY          DECIMAL(18,4)   NOT NULL,
    PRICE             DECIMAL(18,4)   NOT NULL,
    AMOUNT            DECIMAL(18,2)   NOT NULL,
    CURRENCY_CODE     CHAR(3)         NOT NULL,
    STATUS            CHAR(1)         NOT NULL,
    PROCESS_DATE      TIMESTAMP       NOT NULL,
    PROCESS_USER      VARCHAR(8)      NOT NULL,
    PRIMARY KEY (TRANSACTION_ID),
    FOREIGN KEY (PORTFOLIO_ID) REFERENCES PORTFOLIO_MASTER(PORTFOLIO_ID)
);

-- Position Master Table (replaces VSAM KSDS PORTFOLIO.POSITION.VSAM)
-- Composite key: (PORTFOLIO_ID, SYMBOL_ID) per PORTDFN.csd POSFILE definition
-- RECORDSIZE(200), STRINGS(10)
CREATE TABLE POSITION_MASTER (
    PORTFOLIO_ID      CHAR(8)         NOT NULL,
    SYMBOL_ID         CHAR(10)        NOT NULL,
    POSITION_DATE     DATE            NOT NULL,
    QUANTITY          DECIMAL(18,4)   NOT NULL,
    COST_BASIS        DECIMAL(18,2)   NOT NULL,
    MARKET_VALUE      DECIMAL(18,2)   NOT NULL,
    CURRENCY_CODE     CHAR(3)         NOT NULL,
    STATUS            CHAR(1)         NOT NULL DEFAULT 'A',
    LAST_MAINT_DATE   TIMESTAMP       NOT NULL,
    LAST_MAINT_USER   VARCHAR(8)      NOT NULL,
    PRIMARY KEY (PORTFOLIO_ID, SYMBOL_ID)
);

-- Transaction History VSAM Table (replaces VSAM transaction history cluster)
-- Composite key: (PORTFOLIO_ID, TXN_DATE, SEQ)
CREATE TABLE TRANSACTION_HISTORY_VSAM (
    PORTFOLIO_ID      CHAR(8)         NOT NULL,
    TXN_DATE          DATE            NOT NULL,
    SEQ               INTEGER         NOT NULL,
    INVESTMENT_ID     CHAR(10)        NOT NULL,
    TRANSACTION_TYPE  CHAR(2)         NOT NULL,
    QUANTITY          DECIMAL(18,4)   NOT NULL,
    PRICE             DECIMAL(18,4)   NOT NULL,
    AMOUNT            DECIMAL(18,2)   NOT NULL,
    CURRENCY_CODE     CHAR(3)         NOT NULL,
    STATUS            CHAR(1)         NOT NULL DEFAULT 'P',
    COST_BASIS        DECIMAL(18,2)   NOT NULL DEFAULT 0,
    PROCESS_DATE      TIMESTAMP       NOT NULL,
    PROCESS_USER      VARCHAR(8)      NOT NULL,
    PRIMARY KEY (PORTFOLIO_ID, TXN_DATE, SEQ)
);

-- Audit Log Table (from SECMGR.cbl - INSERT INTO AUDITLOG)
CREATE TABLE AUDITLOG (
    AUDIT_ID          BIGINT          GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    AUDIT_TIMESTAMP   TIMESTAMP       NOT NULL,
    USER_ID           VARCHAR(8)      NOT NULL,
    TERMINAL_ID       VARCHAR(4),
    TRANS_ID          VARCHAR(4),
    PROGRAM           VARCHAR(8),
    ACCESS_TYPE       VARCHAR(8),
    RESOURCE_NAME     VARCHAR(50),
    RESPONSE_CODE     INTEGER,
    DETAILS           VARCHAR(500),
    PRIMARY KEY (AUDIT_ID)
);

-- Error Log Table (from ERRLOG.sql)
CREATE TABLE ERRLOG (
    ERROR_ID          BIGINT          GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    ERROR_TIMESTAMP   TIMESTAMP       NOT NULL,
    PROGRAM_ID        CHAR(8)         NOT NULL,
    ERROR_TYPE        CHAR(1)         NOT NULL,
    ERROR_SEVERITY    INTEGER         NOT NULL,
    ERROR_CODE        CHAR(8)         NOT NULL,
    ERROR_MESSAGE     VARCHAR(200)    NOT NULL,
    PROCESS_DATE      DATE            NOT NULL,
    PROCESS_TIME      TIME            NOT NULL,
    USER_ID           CHAR(8)         NOT NULL,
    ADDITIONAL_INFO   VARCHAR(500),
    PRIMARY KEY (ERROR_ID)
);

-- Authorization Table (from SECMGR.cbl - SELECT FROM AUTHFILE)
CREATE TABLE AUTHFILE (
    AUTH_ID           BIGINT          GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    USER_ID           VARCHAR(8)      NOT NULL,
    RESOURCE          VARCHAR(8)      NOT NULL,
    ACCESS_TYPE       VARCHAR(8)      NOT NULL,
    GRANTED_DATE      TIMESTAMP       NOT NULL,
    GRANTED_BY        VARCHAR(8)      NOT NULL,
    PRIMARY KEY (AUTH_ID)
);

-- =============================================================================
-- Indexes for sub-millisecond lookup performance
-- =============================================================================
CREATE INDEX IDX_PORT_MASTER_CLIENT ON PORTFOLIO_MASTER (CLIENT_ID, STATUS);
CREATE INDEX IDX_POSITIONS_DATE ON INVESTMENT_POSITIONS (POSITION_DATE, PORTFOLIO_ID);
CREATE INDEX IDX_TRANS_HIST_PORT ON TRANSACTION_HISTORY (PORTFOLIO_ID, TRANSACTION_DATE);
CREATE INDEX IDX_TRANS_HIST_DATE ON TRANSACTION_HISTORY (TRANSACTION_DATE, PORTFOLIO_ID);
CREATE INDEX IDX_POS_MASTER_PORTFOLIO ON POSITION_MASTER (PORTFOLIO_ID);
CREATE INDEX IDX_POS_MASTER_SYMBOL ON POSITION_MASTER (SYMBOL_ID);
CREATE INDEX IDX_TXN_VSAM_DATE ON TRANSACTION_HISTORY_VSAM (TXN_DATE, PORTFOLIO_ID);
CREATE INDEX IDX_AUDITLOG_TIMESTAMP ON AUDITLOG (AUDIT_TIMESTAMP);
CREATE INDEX IDX_AUDITLOG_USER ON AUDITLOG (USER_ID);
CREATE INDEX IDX_ERRLOG_DATE ON ERRLOG (PROCESS_DATE, ERROR_SEVERITY);
CREATE INDEX IDX_AUTHFILE_USER ON AUTHFILE (USER_ID, RESOURCE, ACCESS_TYPE);
