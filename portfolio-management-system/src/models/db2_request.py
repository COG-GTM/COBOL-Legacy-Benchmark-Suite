"""
DB2 Request Data Model.

Translated from COBOL copybook: src/copybook/online/DB2REQ.cpy

COBOL Source Structure:
    01 DB2-REQUEST-AREA.
       05 DB2-REQUEST-TYPE      PIC X(1).       -> DB2RequestType enum
          88 DB2-CONNECT        VALUE 'C'.
          88 DB2-DISCONNECT     VALUE 'D'.
          88 DB2-STATUS         VALUE 'S'.
       05 DB2-RESPONSE-CODE     PIC S9(8) COMP. -> int
       05 DB2-CONNECTION-TOKEN  PIC X(16).      -> str
       05 DB2-SQLCODE           PIC S9(9) COMP. -> int
       05 DB2-ERROR-MSG         PIC X(80).      -> str

Data Type Mapping Notes:
    PIC S9(8) COMP -> int
        Binary signed integer for response codes.
        Maps directly to Python int.
    PIC S9(9) COMP -> int
        Binary signed integer for SQL codes.
        DB2 SQLCODE values: 0=success, 100=not found, negative=error.
        Common error codes: -803 (duplicate key), -911 (deadlock),
        -913 (timeout), -30081 (connection error).
    PIC X(16) -> str with max_length=16
        Connection token generated by DB2ONLN connection manager.
        Used to identify and reuse connections from the pool.
    PIC X(80) -> str with max_length=80
        Error message field for DB2 error descriptions.

This copybook defines the interface between online programs and the
DB2 connection infrastructure (DB2ONLN, DB2RECV). In the Python
migration, SQLAlchemy handles connection management, making this
model primarily useful for logging and monitoring.
"""

from enum import Enum
from typing import Optional

from pydantic import BaseModel, Field


class DB2RequestType(str, Enum):
    """DB2 request type codes.

    COBOL 88-level condition names from DB2REQ copybook.
    """

    CONNECT = "C"
    DISCONNECT = "D"
    STATUS = "S"


class DB2Request(BaseModel):
    """DB2 request area (DB2-REQUEST-AREA).

    Translated from COBOL copybook DB2REQ.cpy.
    Defines the interface for DB2 connection management operations
    used by the online CICS programs.

    In the Python migration, SQLAlchemy's connection pooling replaces
    the manual connection management. This model is preserved for:
    - Logging connection lifecycle events
    - Monitoring connection pool status
    - Compatibility with audit trail requirements

    Common SQLCODE values (preserved from DB2):
        0    = Success
        100  = Not found (end of data)
        -803 = Duplicate key (23505 in PostgreSQL)
        -911 = Deadlock (40001 in PostgreSQL)
        -913 = Timeout (40003 in PostgreSQL)
        -30081 = Connection error

    Usage:
        # Connection request
        request = DB2Request(
            request_type=DB2RequestType.CONNECT,
        )

        # Successful connection response
        response = DB2Request(
            request_type=DB2RequestType.CONNECT,
            response_code=0,
            connection_token="CONN000000000001",
            sqlcode=0,
        )

        # Connection error
        error = DB2Request(
            request_type=DB2RequestType.CONNECT,
            response_code=8,
            sqlcode=-30081,
            error_msg="Connection to database failed",
        )
    """

    request_type: DB2RequestType = Field(
        ...,
        description=(
            "Type of DB2 operation requested. "
            "COBOL: DB2-REQUEST-TYPE PIC X(1). "
            "C=Connect, D=Disconnect, S=Status."
        ),
    )
    response_code: int = Field(
        default=0,
        description=(
            "Response code (0=success, non-zero=error). "
            "COBOL: DB2-RESPONSE-CODE PIC S9(8) COMP."
        ),
    )
    connection_token: Optional[str] = Field(
        default=None,
        max_length=16,
        description=(
            "Connection identifier token. "
            "COBOL: DB2-CONNECTION-TOKEN PIC X(16). "
            "Generated by DB2ONLN connection manager."
        ),
    )
    sqlcode: int = Field(
        default=0,
        description=(
            "SQL return code from DB2. "
            "COBOL: DB2-SQLCODE PIC S9(9) COMP. "
            "0=success, 100=not found, negative=error."
        ),
    )
    error_msg: Optional[str] = Field(
        default=None,
        max_length=80,
        description=(
            "Error message from DB2. "
            "COBOL: DB2-ERROR-MSG PIC X(80)."
        ),
    )

    @property
    def is_success(self) -> bool:
        """Check if the response indicates success."""
        return self.response_code == 0 and self.sqlcode >= 0

    @property
    def is_not_found(self) -> bool:
        """Check if SQLCODE indicates no data found (end of cursor)."""
        return self.sqlcode == 100

    @property
    def is_deadlock(self) -> bool:
        """Check if SQLCODE indicates a deadlock condition."""
        return self.sqlcode == -911

    @property
    def is_connection_error(self) -> bool:
        """Check if SQLCODE indicates a connection error."""
        return self.sqlcode == -30081
