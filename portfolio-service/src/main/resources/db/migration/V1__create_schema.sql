-- Flyway Migration V1: Create schema for Portfolio Master Service
-- Migrated from COBOL DB2 definitions (db2-definitions.sql, POSHIST.sql, ERRLOG.sql)
-- and VSAM file definitions (vsam-definitions.txt)
-- =====================================================================

-- Portfolio Master Table (from VSAM KSDS PORTMSTR + DB2 PORTFOLIO_MASTER)
CREATE TABLE PORTFOLIO_MASTER (
    PORTFOLIO_ID      VARCHAR(8)       NOT NULL,
    ACCOUNT_NO        VARCHAR(10),
    CLIENT_NAME       VARCHAR(30),
    CLIENT_TYPE       VARCHAR(12),
    ACCOUNT_TYPE      VARCHAR(2),
    BRANCH_ID         VARCHAR(2),
    CLIENT_ID         VARCHAR(10),
    PORTFOLIO_NAME    VARCHAR(50),
    CURRENCY_CODE     VARCHAR(3),
    RISK_LEVEL        CHAR(1),
    CREATE_DATE       DATE,
    CLOSE_DATE        DATE,
    LAST_MAINT_DATE   DATE,
    STATUS            VARCHAR(12)      NOT NULL,
    TOTAL_VALUE       DECIMAL(15,2),
    CASH_BALANCE      DECIMAL(15,2),
    LAST_USER         VARCHAR(8),
    LAST_TRANS_DATE   DATE,
    LAST_MAINT_TIMESTAMP TIMESTAMP,
    PRIMARY KEY (PORTFOLIO_ID)
);

CREATE INDEX IDX_PORT_MASTER_CLIENT ON PORTFOLIO_MASTER (CLIENT_ID, STATUS);

-- Investment Positions Table (from VSAM KSDS POSHIST + DB2 INVESTMENT_POSITIONS)
CREATE TABLE INVESTMENT_POSITIONS (
    PORTFOLIO_ID      VARCHAR(8)       NOT NULL,
    INVESTMENT_ID     VARCHAR(10)      NOT NULL,
    POSITION_DATE     DATE             NOT NULL,
    QUANTITY          DECIMAL(18,4)    NOT NULL,
    COST_BASIS        DECIMAL(18,2)    NOT NULL,
    MARKET_VALUE      DECIMAL(18,2)    NOT NULL,
    CURRENCY_CODE     VARCHAR(3)       NOT NULL,
    STATUS            VARCHAR(12),
    LAST_MAINT_DATE   TIMESTAMP        NOT NULL,
    LAST_MAINT_USER   VARCHAR(8)       NOT NULL,
    PRIMARY KEY (PORTFOLIO_ID, INVESTMENT_ID, POSITION_DATE),
    FOREIGN KEY (PORTFOLIO_ID) REFERENCES PORTFOLIO_MASTER(PORTFOLIO_ID)
);

CREATE INDEX IDX_POSITIONS_DATE ON INVESTMENT_POSITIONS (POSITION_DATE, PORTFOLIO_ID);

-- Transaction History Table (from VSAM KSDS TRANHIST + DB2 TRANSACTION_HISTORY)
CREATE TABLE TRANSACTION_HISTORY (
    TRANSACTION_ID    VARCHAR(20)      NOT NULL,
    PORTFOLIO_ID      VARCHAR(8)       NOT NULL,
    TRANSACTION_DATE  DATE             NOT NULL,
    TRANSACTION_TIME  TIME             NOT NULL,
    INVESTMENT_ID     VARCHAR(10)      NOT NULL,
    TRANSACTION_TYPE  VARCHAR(12)      NOT NULL,
    QUANTITY          DECIMAL(18,4)    NOT NULL,
    PRICE             DECIMAL(18,4)    NOT NULL,
    AMOUNT            DECIMAL(18,2)    NOT NULL,
    CURRENCY_CODE     VARCHAR(3)       NOT NULL,
    STATUS            VARCHAR(12)      NOT NULL,
    PROCESS_DATE      TIMESTAMP        NOT NULL,
    PROCESS_USER      VARCHAR(8)       NOT NULL,
    SEQUENCE_NO       VARCHAR(6),
    PRIMARY KEY (TRANSACTION_ID),
    FOREIGN KEY (PORTFOLIO_ID) REFERENCES PORTFOLIO_MASTER(PORTFOLIO_ID)
);

CREATE INDEX IDX_TRANS_HIST_PORT ON TRANSACTION_HISTORY (PORTFOLIO_ID, TRANSACTION_DATE);
CREATE INDEX IDX_TRANS_HIST_DATE ON TRANSACTION_HISTORY (TRANSACTION_DATE, PORTFOLIO_ID);

-- Position History Table (from DB2 POSHIST)
CREATE TABLE POSITION_HISTORY (
    ID                BIGINT AUTO_INCREMENT PRIMARY KEY,
    ACCOUNT_NO        VARCHAR(10)      NOT NULL,
    PORTFOLIO_ID      VARCHAR(8)       NOT NULL,
    TRANS_DATE        DATE             NOT NULL,
    TRANS_TIME        TIME             NOT NULL,
    TRANS_TYPE        VARCHAR(2)       NOT NULL,
    SECURITY_ID       VARCHAR(12)      NOT NULL,
    QUANTITY          DECIMAL(15,3)    NOT NULL,
    PRICE             DECIMAL(15,3)    NOT NULL,
    AMOUNT            DECIMAL(15,2)    NOT NULL,
    FEES              DECIMAL(15,2)    DEFAULT 0,
    TOTAL_AMOUNT      DECIMAL(15,2)    NOT NULL,
    COST_BASIS        DECIMAL(15,2)    NOT NULL,
    GAIN_LOSS         DECIMAL(15,2)    NOT NULL,
    PROCESS_DATE      DATE             NOT NULL,
    PROCESS_TIME      TIME             NOT NULL,
    PROGRAM_ID        VARCHAR(8)       NOT NULL,
    USER_ID           VARCHAR(8)       NOT NULL,
    AUDIT_TIMESTAMP   TIMESTAMP        NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IDX_POSHIST_SEC ON POSITION_HISTORY (SECURITY_ID, TRANS_DATE);
CREATE INDEX IDX_POSHIST_PROC ON POSITION_HISTORY (PROCESS_DATE, PROGRAM_ID);

-- Audit Log Table (from COBOL AUDITLOG.cpy)
CREATE TABLE AUDIT_LOG (
    ID                BIGINT AUTO_INCREMENT PRIMARY KEY,
    AUDIT_TIMESTAMP   TIMESTAMP        NOT NULL,
    SYSTEM_ID         VARCHAR(8),
    USER_ID           VARCHAR(8),
    PROGRAM_NAME      VARCHAR(8),
    TERMINAL_ID       VARCHAR(8),
    AUDIT_TYPE        VARCHAR(4),
    AUDIT_ACTION      VARCHAR(8),
    AUDIT_STATUS      VARCHAR(4),
    PORTFOLIO_ID      VARCHAR(8),
    ACCOUNT_NO        VARCHAR(10),
    BEFORE_IMAGE      VARCHAR(500),
    AFTER_IMAGE       VARCHAR(500),
    MESSAGE           VARCHAR(200)
);

CREATE INDEX IDX_AUDIT_PORT ON AUDIT_LOG (PORTFOLIO_ID, AUDIT_TIMESTAMP);

-- Error Log Table (from DB2 ERRLOG)
CREATE TABLE ERROR_LOG (
    ID                BIGINT AUTO_INCREMENT PRIMARY KEY,
    ERROR_TIMESTAMP   TIMESTAMP        NOT NULL,
    PROGRAM_ID        VARCHAR(8)       NOT NULL,
    ERROR_TYPE        CHAR(1)          NOT NULL,
    ERROR_SEVERITY    INTEGER          NOT NULL,
    ERROR_CODE        VARCHAR(8)       NOT NULL,
    ERROR_MESSAGE     VARCHAR(200)     NOT NULL,
    PROCESS_DATE      DATE             NOT NULL,
    PROCESS_TIME      TIME             NOT NULL,
    USER_ID           VARCHAR(8)       NOT NULL,
    ADDITIONAL_INFO   VARCHAR(500)
);

CREATE INDEX IDX_ERRLOG_DATE ON ERROR_LOG (PROCESS_DATE, ERROR_SEVERITY);

-- Batch Checkpoint Table (from COBOL CKPRST.cpy)
CREATE TABLE BATCH_CHECKPOINT (
    PROGRAM_ID        VARCHAR(8)       NOT NULL,
    RUN_DATE          DATE             NOT NULL,
    RUN_TIME          TIME,
    STATUS            VARCHAR(12)      NOT NULL,
    RECORDS_READ      BIGINT           DEFAULT 0,
    RECORDS_PROCESSED BIGINT           DEFAULT 0,
    RECORDS_ERROR     BIGINT           DEFAULT 0,
    RESTART_COUNT     INTEGER          DEFAULT 0,
    LAST_KEY          VARCHAR(50),
    LAST_CHECKPOINT_TIME TIMESTAMP,
    PHASE             VARCHAR(2),
    COMMIT_FREQUENCY  INTEGER          DEFAULT 1000,
    MAX_ERRORS        INTEGER          DEFAULT 100,
    MAX_RESTARTS      INTEGER          DEFAULT 3,
    RESTART_MODE      CHAR(1)          DEFAULT 'N',
    PRIMARY KEY (PROGRAM_ID, RUN_DATE)
);

-- Batch Control Table (from COBOL BCHCTL.cpy)
CREATE TABLE BATCH_CONTROL (
    ID                BIGINT AUTO_INCREMENT PRIMARY KEY,
    JOB_NAME          VARCHAR(8)       NOT NULL,
    PROCESS_DATE      DATE             NOT NULL,
    SEQUENCE_NO       INTEGER          NOT NULL,
    STATUS            VARCHAR(12)      NOT NULL,
    STEP_NAME         VARCHAR(8),
    PROGRAM_NAME      VARCHAR(8),
    START_TIME        TIMESTAMP,
    END_TIME          TIMESTAMP,
    RETURN_CODE       INTEGER,
    ERROR_DESC        VARCHAR(80),
    RESTART_COUNT     INTEGER          DEFAULT 0,
    ATTEMPT_TIMESTAMP TIMESTAMP,
    COMPLETE_TIMESTAMP TIMESTAMP
);

CREATE INDEX IDX_BATCH_CTRL_JOB ON BATCH_CONTROL (JOB_NAME, PROCESS_DATE);
