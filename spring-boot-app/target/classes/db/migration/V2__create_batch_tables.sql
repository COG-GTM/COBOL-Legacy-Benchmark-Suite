CREATE TABLE prerequisite_job (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    parent_job_name     VARCHAR(8),
    parent_process_date VARCHAR(8),
    parent_sequence_no  INTEGER,
    prereq_name         VARCHAR(8)  NOT NULL,
    prereq_seq          INTEGER,
    prereq_rc           INTEGER
);

CREATE TABLE batch_control_record (
    job_name            VARCHAR(8)  NOT NULL,
    process_date        VARCHAR(8)  NOT NULL,
    sequence_no         INTEGER     NOT NULL,
    status              VARCHAR(10) NOT NULL,
    step_name           VARCHAR(8),
    program_name        VARCHAR(8),
    start_time          VARCHAR(8),
    end_time            VARCHAR(8),
    prereq_count        INTEGER,
    return_code         INTEGER,
    error_desc          VARCHAR(80),
    restart_count       INTEGER,
    attempt_timestamp   TIMESTAMP,
    complete_timestamp  TIMESTAMP,
    PRIMARY KEY (job_name, process_date, sequence_no)
);

CREATE TABLE process_dependency (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    parent_process_id   VARCHAR(8),
    parent_version      INTEGER,
    dep_id              VARCHAR(8)  NOT NULL,
    dep_type            VARCHAR(1)  NOT NULL,
    dep_rc              INTEGER
);

CREATE TABLE process_sequence_record (
    process_id          VARCHAR(8)  NOT NULL,
    version             INTEGER     NOT NULL,
    description         VARCHAR(30),
    type                VARCHAR(10) NOT NULL,
    frequency           VARCHAR(10) NOT NULL,
    start_time          INTEGER,
    max_time            INTEGER,
    program             VARCHAR(8),
    parm                VARCHAR(50),
    max_return_code     INTEGER,
    restartable         BOOLEAN,
    active_days         VARCHAR(7),
    month_end           VARCHAR(1),
    holiday_run         VARCHAR(1),
    recovery_program    VARCHAR(8),
    recovery_parm       VARCHAR(50),
    error_limit         INTEGER,
    create_date         DATE,
    create_user         VARCHAR(8),
    update_date         DATE,
    update_user         VARCHAR(8),
    PRIMARY KEY (process_id, version)
);

CREATE TABLE checkpoint_control (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    program_id          VARCHAR(8)  NOT NULL,
    run_date            VARCHAR(8)  NOT NULL,
    run_time            VARCHAR(6),
    status              VARCHAR(12) NOT NULL,
    records_read        BIGINT,
    records_processed   BIGINT,
    records_error       BIGINT,
    restart_count       INTEGER,
    last_key            VARCHAR(50),
    last_time           TIMESTAMP,
    phase               VARCHAR(12),
    file1_name          VARCHAR(8),
    file1_pos           VARCHAR(50),
    file1_status        VARCHAR(2),
    file2_name          VARCHAR(8),
    file2_pos           VARCHAR(50),
    file2_status        VARCHAR(2),
    file3_name          VARCHAR(8),
    file3_pos           VARCHAR(50),
    file3_status        VARCHAR(2),
    file4_name          VARCHAR(8),
    file4_pos           VARCHAR(50),
    file4_status        VARCHAR(2),
    file5_name          VARCHAR(8),
    file5_pos           VARCHAR(50),
    file5_status        VARCHAR(2),
    commit_frequency    INTEGER DEFAULT 1000,
    max_errors          INTEGER DEFAULT 100,
    max_restarts        INTEGER DEFAULT 3,
    restart_mode        VARCHAR(1)
);
