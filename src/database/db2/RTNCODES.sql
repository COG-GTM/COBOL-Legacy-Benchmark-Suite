--=====================================================================

CREATE TABLESPACE RTNCODES
  IN POSMVP
  USING STOGROUP POSMVPSG
  PRIQTY 1440
  SECQTY 720
  SEGSIZE 32
  COMPRESS YES;

CREATE TABLE RTNCODES
  (TIMESTAMP         CHAR(21)        NOT NULL,
   PROGRAM_ID        CHAR(8)         NOT NULL,
   RETURN_CODE       SMALLINT        NOT NULL,
   HIGHEST_CODE      SMALLINT        NOT NULL,
   STATUS_CODE       CHAR(1)         NOT NULL,
   MESSAGE_TEXT      CHAR(80))
  IN POSMVP.RTNCODES;

-- Primary Index
CREATE UNIQUE INDEX RTNCODES_PK
  ON RTNCODES
  (TIMESTAMP ASC,
   PROGRAM_ID ASC)
  CLUSTER;

ALTER TABLE RTNCODES
  ADD CONSTRAINT RTNCODES_PK
  PRIMARY KEY (TIMESTAMP, PROGRAM_ID);

-- Secondary Index for program analysis
CREATE INDEX RTNCODES_IX1
  ON RTNCODES
  (PROGRAM_ID ASC,
   TIMESTAMP ASC);

-- Table Comments
COMMENT ON TABLE RTNCODES IS
  'Return Code Logging Table - Stores program return codes and status';

COMMENT ON COLUMN RTNCODES.TIMESTAMP IS
  'ISO timestamp from CURRENT-DATE function (YYYYMMDDHHMMSSFFFFFFF)';
COMMENT ON COLUMN RTNCODES.STATUS_CODE IS
  'Status (S=Success, W=Warning, E=Error, F=Severe)';

-- Grants
GRANT SELECT, INSERT ON RTNCODES TO POSAPP;
GRANT SELECT ON RTNCODES TO POSRPT;
GRANT EXECUTE ON PROCEDURE SP_LOG_RETURN_CODE TO POSAPP;

-- Logging Procedure
CREATE PROCEDURE SP_LOG_RETURN_CODE
  (IN  P_PROGRAM_ID     CHAR(8),
   IN  P_RETURN_CODE    SMALLINT,
   IN  P_HIGHEST_CODE   SMALLINT,
   IN  P_STATUS_CODE    CHAR(1),
   IN  P_MESSAGE_TEXT   CHAR(80),
   OUT P_RESULT_CODE    INTEGER)
  LANGUAGE SQL
BEGIN
  DECLARE V_TIMESTAMP CHAR(21);
  SET V_TIMESTAMP = CHAR(CURRENT TIMESTAMP, ISO);

  INSERT INTO RTNCODES
    (TIMESTAMP, PROGRAM_ID, RETURN_CODE,
     HIGHEST_CODE, STATUS_CODE, MESSAGE_TEXT)
  VALUES
    (V_TIMESTAMP, P_PROGRAM_ID, P_RETURN_CODE,
     P_HIGHEST_CODE, P_STATUS_CODE, P_MESSAGE_TEXT);

  SET P_RESULT_CODE = 0;
END;  