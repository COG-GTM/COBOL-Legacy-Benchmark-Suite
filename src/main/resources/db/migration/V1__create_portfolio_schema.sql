-- Schema derived from the copybooks PORTFLIO, POSREC, TRNREC, AUDITLOG and the DB2 table POSHIST.

CREATE TABLE PORTFOLIO (
    PORTFOLIO_ID     VARCHAR(8)      NOT NULL,
    ACCOUNT_NO       VARCHAR(10)     NOT NULL,
    CLIENT_NAME      VARCHAR(30)     NOT NULL,
    CLIENT_TYPE      VARCHAR(1),
    CREATE_DATE      DATE,
    LAST_MAINT_DATE  DATE,
    STATUS           VARCHAR(1)      NOT NULL,
    TOTAL_VALUE      NUMERIC(15, 2)  NOT NULL,
    CASH_BALANCE     NUMERIC(15, 2)  NOT NULL,
    LAST_USER        VARCHAR(8),
    LAST_TRANS       VARCHAR(8),
    PRIMARY KEY (PORTFOLIO_ID, ACCOUNT_NO)
);

CREATE INDEX IX_PORTFOLIO_ACCOUNT ON PORTFOLIO (ACCOUNT_NO);

CREATE TABLE POSITION (
    ID               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    PORTFOLIO_ID     VARCHAR(8)      NOT NULL,
    POSITION_DATE    DATE            NOT NULL,
    INVESTMENT_ID    VARCHAR(10)     NOT NULL,
    QUANTITY         NUMERIC(15, 4)  NOT NULL,
    COST_BASIS       NUMERIC(15, 2)  NOT NULL,
    MARKET_VALUE     NUMERIC(15, 2)  NOT NULL,
    CURRENCY         VARCHAR(3)      NOT NULL,
    STATUS           VARCHAR(1)      NOT NULL,
    LAST_MAINT_TS    TIMESTAMP,
    LAST_MAINT_USER  VARCHAR(8),
    CONSTRAINT UK_POSITION UNIQUE (PORTFOLIO_ID, INVESTMENT_ID, POSITION_DATE)
);

CREATE TABLE PORTFOLIO_TRANSACTION (
    ID               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    TRANS_DATE       DATE            NOT NULL,
    TRANS_TIME       TIME            NOT NULL,
    PORTFOLIO_ID     VARCHAR(8)      NOT NULL,
    INVESTMENT_ID    VARCHAR(10),
    TRANS_TYPE       VARCHAR(2)      NOT NULL,
    QUANTITY         NUMERIC(15, 4)  NOT NULL,
    PRICE            NUMERIC(15, 4)  NOT NULL,
    AMOUNT           NUMERIC(15, 2)  NOT NULL,
    CURRENCY         VARCHAR(3)      NOT NULL,
    STATUS           VARCHAR(1)      NOT NULL,
    STATUS_MESSAGE   VARCHAR(80),
    PROCESS_TS       TIMESTAMP,
    PROCESS_USER     VARCHAR(8)
);

CREATE INDEX IX_TRANSACTION_PORTFOLIO ON PORTFOLIO_TRANSACTION (PORTFOLIO_ID, TRANS_DATE);

CREATE TABLE POSITION_HISTORY (
    ID               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ACCOUNT_NO       VARCHAR(10)     NOT NULL,
    PORTFOLIO_ID     VARCHAR(8)      NOT NULL,
    TRANS_DATE       DATE            NOT NULL,
    TRANS_TIME       TIME            NOT NULL,
    TRANS_TYPE       VARCHAR(2)      NOT NULL,
    SECURITY_ID      VARCHAR(12)     NOT NULL,
    QUANTITY         NUMERIC(15, 4)  NOT NULL,
    PRICE            NUMERIC(15, 4)  NOT NULL,
    AMOUNT           NUMERIC(15, 2)  NOT NULL,
    FEES             NUMERIC(15, 2)  NOT NULL,
    TOTAL_AMOUNT     NUMERIC(15, 2)  NOT NULL,
    COST_BASIS       NUMERIC(15, 2)  NOT NULL,
    GAIN_LOSS        NUMERIC(15, 2)  NOT NULL,
    PROGRAM_ID       VARCHAR(8)      NOT NULL,
    USER_ID          VARCHAR(8)      NOT NULL,
    AUDIT_TS         TIMESTAMP       NOT NULL
);

CREATE INDEX IX_HISTORY_ACCOUNT ON POSITION_HISTORY (ACCOUNT_NO, TRANS_DATE);

CREATE TABLE AUDIT_LOG (
    ID               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    AUDIT_TS         TIMESTAMP       NOT NULL,
    SYSTEM_ID        VARCHAR(16),
    USER_ID          VARCHAR(64),
    PROGRAM          VARCHAR(8),
    AUDIT_TYPE       VARCHAR(4)      NOT NULL,
    ACTION           VARCHAR(8)      NOT NULL,
    STATUS           VARCHAR(4)      NOT NULL,
    PORTFOLIO_ID     VARCHAR(8),
    ACCOUNT_NO       VARCHAR(10),
    REASON_CODE      VARCHAR(2),
    BEFORE_IMAGE     VARCHAR(400),
    AFTER_IMAGE      VARCHAR(400),
    MESSAGE          VARCHAR(100)
);

CREATE INDEX IX_AUDIT_PORTFOLIO ON AUDIT_LOG (PORTFOLIO_ID);
